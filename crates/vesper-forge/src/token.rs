//! Host-owned tokens and the bounded quotation representation.

use serde::{Deserialize, Serialize};

use crate::identity::{ExpansionId, ScopeSet, SpliceHandle, Symbol};
use crate::registry::{DefId, PackageId};

#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub enum Delim {
    Paren,
    Bracket,
    Brace,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub enum TokenKind {
    Ident,
    Punct,
    Int,
    Str,
    Open(Delim),
    Close(Delim),
}

/// Where a token was *emitted* from. This is independent of which package
/// defines the global a token may resolve to.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub enum Origin {
    /// Source text of `package`, lexed by the host itself.
    Source { package: PackageId },
    /// Generated by a macro during this expansion.
    Expansion(ExpansionId),
}

/// A guest- or source-reported location. Display data only: it never
/// contributes to provenance, hygiene or authority decisions.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub struct ReportedSpan {
    pub file: u32,
    pub start: u32,
    pub end: u32,
}

/// A token whose scopes and origin were assigned by the host.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct HostToken {
    pub(crate) kind: TokenKind,
    pub(crate) text: Symbol,
    pub(crate) scopes: ScopeSet,
    pub(crate) origin: Origin,
    /// An unvalidated pre-resolved global claim; the resolver checks it
    /// against the registry and the emitting package's visibility.
    pub(crate) claimed_def: Option<DefId>,
    pub(crate) reported_span: Option<ReportedSpan>,
}

impl HostToken {
    pub fn kind(&self) -> TokenKind {
        self.kind
    }
    pub fn text(&self) -> Symbol {
        self.text
    }
    pub fn scopes(&self) -> &ScopeSet {
        &self.scopes
    }
    pub fn origin(&self) -> Origin {
        self.origin
    }
    pub fn claimed_def(&self) -> Option<DefId> {
        self.claimed_def
    }
    pub fn reported_span(&self) -> Option<ReportedSpan> {
        self.reported_span
    }
}

/// A token produced by macro code. It has no scopes or origin of its own:
/// the host assigns both when the expansion finishes.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct GeneratedToken {
    pub kind: TokenKind,
    pub text: String,
    pub claimed_def: Option<DefId>,
    pub reported_span: Option<ReportedSpan>,
}

impl GeneratedToken {
    pub fn new(kind: TokenKind, text: impl Into<String>) -> Self {
        Self {
            kind,
            text: text.into(),
            claimed_def: None,
            reported_span: None,
        }
    }
    pub fn ident(text: impl Into<String>) -> Self {
        Self::new(TokenKind::Ident, text)
    }
    pub fn punct(text: impl Into<String>) -> Self {
        Self::new(TokenKind::Punct, text)
    }
    pub fn with_def(mut self, def: DefId) -> Self {
        self.claimed_def = Some(def);
        self
    }
}

/// One quotation element: generated syntax or an antiquote of caller syntax.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum QuoteItem {
    Token(GeneratedToken),
    /// `$x`: splice the caller syntax the host stored under this handle.
    Splice(SpliceHandle),
}

/// A flat quotation with antiquotes, as a structured (non-flat) macro ABI
/// would return it.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct Quotation {
    pub items: Vec<QuoteItem>,
}

impl Quotation {
    pub fn new() -> Self {
        Self::default()
    }
    pub fn token(mut self, t: GeneratedToken) -> Self {
        self.items.push(QuoteItem::Token(t));
        self
    }
    pub fn splice(mut self, h: SpliceHandle) -> Self {
        self.items.push(QuoteItem::Splice(h));
        self
    }
    /// Appends whitespace-separated generated tokens lexed by
    /// [`crate::lex_fragment`] rules.
    pub fn text(mut self, src: &str) -> Self {
        for t in crate::lex::lex_generated(src) {
            self.items.push(QuoteItem::Token(t));
        }
        self
    }
}

/// Bounds on quotation/expansion size. Violations fail the expansion.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct QuoteLimits {
    pub max_items: usize,
    pub max_output_tokens: usize,
    pub max_text_bytes: usize,
    pub max_splices: usize,
    /// Maximum delimiter and syntactic nesting depth.
    pub max_depth: usize,
}

impl Default for QuoteLimits {
    fn default() -> Self {
        Self {
            max_items: 1 << 16,
            max_output_tokens: 1 << 18,
            max_text_bytes: 1 << 22,
            max_splices: 1 << 12,
            max_depth: 128,
        }
    }
}
