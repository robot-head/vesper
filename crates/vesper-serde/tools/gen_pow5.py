#!/usr/bin/env python3
"""Generate src/pow5.rs: 128-bit truncated significands of 5^q for
q in [-342, 308], as used by the Eisel-Lemire algorithm (Lemire, "Number
Parsing at a Gigabyte per Second", 2021, and Mushtak & Lemire 2022).

Positive powers: the top 128 bits of 5^q, truncated. Negative powers: the
128 most significant bits of floor(2^b / 5^-q) + 1, with b = z + 127 for
q >= -27 (z the bit length of 5^-q) and b = 2z + 128 below, matching the
reference tables of fast_float and Rust's core::num::dec2flt.
`tests/float_lemire.rs` recomputes every entry with an independent big
integer and checks it."""
import sys

LO, HI = -342, 308

def entry(q):
    if q >= 0:
        p = 5 ** q
        while p < (1 << 127):
            p <<= 1
        while p >= (1 << 128):
            p >>= 1
        return p
    p = 5 ** -q
    z = p.bit_length()
    # Small negative powers: 2^(z+127) / 5^-q already has 128 bits, so the
    # +1 survives; larger ones use a wider quotient that is then truncated.
    b = z + 127 if q >= -27 else 2 * z + 2 * 64
    c = (1 << b) // p + 1
    while c >= (1 << 128):
        c >>= 1
    return c

out = ["// @generated by tools/gen_pow5.py; do not edit.",
       "/// `(high, low)` 64-bit halves of the 128-bit significand of 5^q,",
       f"/// for q = {LO} at index 0 through q = {HI}.",
       f"pub(crate) static POW5_128: [(u64, u64); {HI - LO + 1}] = ["]
for q in range(LO, HI + 1):
    v = entry(q)
    out.append(f"    (0x{v >> 64:016x}, 0x{v & ((1 << 64) - 1):016x}),")
out.append("];")
sys.stdout.write("\n".join(out) + "\n")
