//! Declarative step configuration and its validation.
//!
//! A step sees exactly: the declared read-only input mounts, one dedicated
//! writable output directory at [`OUTPUT_GUEST_PATH`], no environment
//! variables, no arguments, no sockets, empty stdin, bounded stdout/stderr,
//! a fixed wall clock, a non-advancing monotonic clock, and seeded
//! deterministic randomness.

use std::path::{Path, PathBuf};
use std::time::Duration;

use serde::{Deserialize, Serialize};

use crate::transport::TransportLimits;

/// Guest path of the dedicated writable output directory (`$OUT_DIR`).
pub const OUTPUT_GUEST_PATH: &str = "/out";

/// One read-only directory exposed to the guest.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct InputMount {
    pub host_path: PathBuf,
    /// Absolute, normalized guest path such as `/in/proto`.
    pub guest_path: String,
}

impl InputMount {
    pub fn new(host_path: impl Into<PathBuf>, guest_path: impl Into<String>) -> Self {
        Self {
            host_path: host_path.into(),
            guest_path: guest_path.into(),
        }
    }
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct ResourceLimits {
    /// Wasmtime fuel units (roughly one per executed Wasm operator).
    pub fuel: u64,
    /// Aggregate bytes across all linear memories in the store.
    pub max_memory_bytes: usize,
    /// Aggregate elements across all tables in the store.
    pub max_table_elements: usize,
    pub max_instances: usize,
    pub max_memories: usize,
    pub max_tables: usize,
    /// Captured stdout/stderr bytes each. Writes past this trap the guest.
    pub max_stdio_bytes: usize,
    /// Post-run bound on the output directory's total file bytes.
    pub max_output_bytes: u64,
    /// Post-run bound on the number of output entries.
    pub max_output_entries: usize,
    /// Non-deterministic safety net for time spent blocked in host calls
    /// (such as `sleep`), which fuel does not meter.
    pub wall_clock_backstop: Duration,
    pub transport: TransportLimits,
}

impl Default for ResourceLimits {
    fn default() -> Self {
        Self {
            fuel: 50_000_000,
            max_memory_bytes: 64 << 20,
            max_table_elements: 100_000,
            max_instances: 32,
            max_memories: 8,
            max_tables: 32,
            max_stdio_bytes: 64 << 10,
            max_output_bytes: 64 << 20,
            max_output_entries: 4096,
            wall_clock_backstop: Duration::from_secs(30),
            transport: TransportLimits::default(),
        }
    }
}

/// Values the guest observes for clocks and randomness.
/// The default is epoch zero, monotonic zero, seed zero.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct Determinism {
    /// Fixed `wasi:clocks/wall-clock` reading, nanoseconds since the epoch.
    pub wall_clock_ns: u64,
    /// Fixed `wasi:clocks/monotonic-clock` reading. The clock never advances.
    pub monotonic_ns: u64,
    /// Seed for `wasi:random/random`, `insecure` and `insecure-seed`.
    /// The generated bytes are reproducible and therefore NOT secret.
    pub random_seed: u64,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct StepConfig {
    pub inputs: Vec<InputMount>,
    /// Must exist, be a directory, and be empty.
    pub output_dir: PathBuf,
    pub limits: ResourceLimits,
    pub determinism: Determinism,
}

impl StepConfig {
    pub fn new(output_dir: impl Into<PathBuf>) -> Self {
        Self {
            inputs: Vec::new(),
            output_dir: output_dir.into(),
            limits: ResourceLimits::default(),
            determinism: Determinism::default(),
        }
    }

    pub fn input(mut self, host_path: impl Into<PathBuf>, guest_path: impl Into<String>) -> Self {
        self.inputs.push(InputMount::new(host_path, guest_path));
        self
    }
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum ConfigError {
    GuestPathNotAbsolute { guest_path: String },
    GuestPathNotNormalized { guest_path: String },
    GuestPathIsRoot,
    GuestPathOverlapsOutput { guest_path: String },
    GuestPathsNested { outer: String, inner: String },
    HostPathMissing { host_path: PathBuf, reason: String },
    HostPathNotDirectory { host_path: PathBuf },
    OutputNotEmpty { host_path: PathBuf },
    HostPathsOverlap { input: PathBuf, output: PathBuf },
    ZeroLimit { field: String },
}

/// A configuration whose host paths are canonical and checked.
#[derive(Clone, Debug)]
pub(crate) struct ValidatedLayout {
    pub inputs: Vec<(PathBuf, String)>,
    pub output_dir: PathBuf,
}

fn guest_components(path: &str) -> Result<Vec<&str>, ConfigError> {
    if !path.starts_with('/') {
        return Err(ConfigError::GuestPathNotAbsolute {
            guest_path: path.to_owned(),
        });
    }
    let parts: Vec<&str> = path[1..].split('/').collect();
    if parts == [""] {
        return Err(ConfigError::GuestPathIsRoot);
    }
    if parts
        .iter()
        .any(|p| p.is_empty() || *p == "." || *p == ".." || p.contains('\\') || p.contains('\0'))
    {
        return Err(ConfigError::GuestPathNotNormalized {
            guest_path: path.to_owned(),
        });
    }
    Ok(parts)
}

fn is_prefix(a: &[&str], b: &[&str]) -> bool {
    a.len() <= b.len() && a.iter().zip(b).all(|(x, y)| x == y)
}

fn canonical_dir(path: &Path) -> Result<PathBuf, ConfigError> {
    let canon = path
        .canonicalize()
        .map_err(|e| ConfigError::HostPathMissing {
            host_path: path.to_owned(),
            reason: e.to_string(),
        })?;
    if !canon.is_dir() {
        return Err(ConfigError::HostPathNotDirectory { host_path: canon });
    }
    Ok(canon)
}

impl StepConfig {
    pub(crate) fn validate(&self) -> Result<ValidatedLayout, ConfigError> {
        let l = &self.limits;
        for (field, zero) in [
            ("fuel", l.fuel == 0),
            ("max_memory_bytes", l.max_memory_bytes == 0),
            ("max_instances", l.max_instances == 0),
            ("wall_clock_backstop", l.wall_clock_backstop.is_zero()),
        ] {
            if zero {
                return Err(ConfigError::ZeroLimit {
                    field: field.to_owned(),
                });
            }
        }

        let out_parts = guest_components(OUTPUT_GUEST_PATH)?;
        let mut guest_parts = Vec::new();
        for m in &self.inputs {
            let parts = guest_components(&m.guest_path)?;
            if is_prefix(&parts, &out_parts) || is_prefix(&out_parts, &parts) {
                return Err(ConfigError::GuestPathOverlapsOutput {
                    guest_path: m.guest_path.clone(),
                });
            }
            for (other, other_parts) in &guest_parts {
                let (other, other_parts): (&String, &Vec<&str>) = (other, other_parts);
                if is_prefix(other_parts, &parts) {
                    return Err(ConfigError::GuestPathsNested {
                        outer: other.clone(),
                        inner: m.guest_path.clone(),
                    });
                }
                if is_prefix(&parts, other_parts) {
                    return Err(ConfigError::GuestPathsNested {
                        outer: m.guest_path.clone(),
                        inner: other.clone(),
                    });
                }
            }
            guest_parts.push((m.guest_path.clone(), parts));
        }

        let output_dir = canonical_dir(&self.output_dir)?;
        let non_empty = std::fs::read_dir(&output_dir)
            .map_err(|e| ConfigError::HostPathMissing {
                host_path: output_dir.clone(),
                reason: e.to_string(),
            })?
            .next()
            .is_some();
        if non_empty {
            return Err(ConfigError::OutputNotEmpty {
                host_path: output_dir,
            });
        }

        let mut inputs = Vec::new();
        for m in &self.inputs {
            let host = canonical_dir(&m.host_path)?;
            if host.starts_with(&output_dir) || output_dir.starts_with(&host) {
                return Err(ConfigError::HostPathsOverlap {
                    input: host,
                    output: output_dir,
                });
            }
            inputs.push((host, m.guest_path.clone()));
        }
        Ok(ValidatedLayout { inputs, output_dir })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn dirs() -> (tempfile::TempDir, PathBuf, PathBuf) {
        let root = tempfile::tempdir().unwrap();
        let input = root.path().join("in");
        let out = root.path().join("out");
        std::fs::create_dir(&input).unwrap();
        std::fs::create_dir(&out).unwrap();
        (root, input, out)
    }

    #[test]
    fn valid_layout_is_canonical() {
        let (_root, input, out) = dirs();
        let v = StepConfig::new(&out)
            .input(&input, "/in/proto")
            .validate()
            .unwrap();
        assert_eq!(v.output_dir, out.canonicalize().unwrap());
        assert_eq!(v.inputs[0].1, "/in/proto");
    }

    #[test]
    fn guest_paths_must_be_absolute_and_normalized() {
        let (_root, input, out) = dirs();
        for (g, want) in [
            ("in", "NotAbsolute"),
            ("/", "IsRoot"),
            ("/in/../etc", "NotNormalized"),
            ("/in//x", "NotNormalized"),
            ("/in/./x", "NotNormalized"),
            ("/in/", "NotNormalized"),
        ] {
            let err = StepConfig::new(&out)
                .input(&input, g)
                .validate()
                .unwrap_err();
            assert!(format!("{err:?}").contains(want), "{g}: {err:?}");
        }
    }

    #[test]
    fn guest_paths_must_not_overlap_output_or_each_other() {
        let (_root, input, out) = dirs();
        for g in ["/out", "/out/x"] {
            let err = StepConfig::new(&out)
                .input(&input, g)
                .validate()
                .unwrap_err();
            assert!(matches!(err, ConfigError::GuestPathOverlapsOutput { .. }));
        }
        let err = StepConfig::new(&out)
            .input(&input, "/in")
            .input(&input, "/in/sub")
            .validate()
            .unwrap_err();
        assert!(matches!(err, ConfigError::GuestPathsNested { .. }));
        let err = StepConfig::new(&out)
            .input(&input, "/in/a")
            .input(&input, "/in/a")
            .validate()
            .unwrap_err();
        assert!(matches!(err, ConfigError::GuestPathsNested { .. }));
    }

    #[test]
    fn output_must_be_dedicated_empty_and_disjoint() {
        let (root, input, out) = dirs();
        std::fs::write(out.join("stale"), b"x").unwrap();
        assert!(matches!(
            StepConfig::new(&out).validate(),
            Err(ConfigError::OutputNotEmpty { .. })
        ));
        std::fs::remove_file(out.join("stale")).unwrap();

        // Input that contains the output directory.
        assert!(matches!(
            StepConfig::new(&out)
                .input(root.path(), "/in/all")
                .validate(),
            Err(ConfigError::HostPathsOverlap { .. })
        ));
        // Output nested in an input.
        let nested = input.join("gen");
        std::fs::create_dir(&nested).unwrap();
        assert!(matches!(
            StepConfig::new(&nested).input(&input, "/in/x").validate(),
            Err(ConfigError::HostPathsOverlap { .. })
        ));
    }

    #[test]
    fn missing_paths_and_zero_limits_rejected() {
        let (root, _input, out) = dirs();
        assert!(matches!(
            StepConfig::new(root.path().join("nope")).validate(),
            Err(ConfigError::HostPathMissing { .. })
        ));
        let file = root.path().join("file");
        std::fs::write(&file, b"").unwrap();
        assert!(matches!(
            StepConfig::new(&out).input(&file, "/in/f").validate(),
            Err(ConfigError::HostPathNotDirectory { .. })
        ));
        let mut cfg = StepConfig::new(&out);
        cfg.limits.fuel = 0;
        assert_eq!(
            cfg.validate().unwrap_err(),
            ConfigError::ZeroLimit {
                field: "fuel".into()
            }
        );
    }
}
