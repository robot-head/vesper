//! Generates `vesper/src/width.ves`, the character tables of the Vesper
//! port's terminal renderer, from the crates the Rust build uses: the
//! display width of every char from unicode-width 0.1.14 (the version
//! ariadne 0.5.1 resolves to here, `UnicodeWidthChar::width`, with ariadne's
//! `unwrap_or(1)` for control characters) and Rust's `char::is_whitespace`.
//!
//! Run `cargo run -p vesper-diagnostics-seed --example width_table >
//! crates/vesper-diagnostics/vesper/src/width.ves`; the test
//! `width_table_is_generated` (tests/port_tables.rs) fails when the committed
//! file differs from this output.
use unicode_width::UnicodeWidthChar;

/// Maximal runs of code points with the same value, as (first, last, value),
/// leaving out the runs whose value is `skip`.
fn runs(value: impl Fn(char) -> u64, skip: u64) -> Vec<(u32, u32, u64)> {
    let mut out: Vec<(u32, u32, u64)> = Vec::new();
    for cp in 0..=0x10_ffffu32 {
        // Surrogates are not chars and never reach the renderer; they join
        // whatever run they are in.
        let v = match char::from_u32(cp) {
            Some(c) => value(c),
            None => match out.last() {
                Some(&(_, last, v)) if last + 1 == cp => v,
                _ => skip,
            },
        };
        match out.last_mut() {
            Some((_, last, prev)) if *last + 1 == cp && *prev == v => *last = cp,
            _ => out.push((cp, cp, v)),
        }
    }
    out.retain(|&(_, _, v)| v != skip);
    out
}

fn table(name: &str, rows: &[(u32, u32, u64)], with_value: bool) -> String {
    // `vesper fmt`'s layout: one line when it fits in 100 columns, else one
    // element per line.
    let array = |suffix: &str, f: &dyn Fn(&(u32, u32, u64)) -> u64| {
        let items: Vec<String> = rows.iter().map(|r| f(r).to_string()).collect();
        let head = format!("const {name}_{suffix}: [u64; {}] = [", rows.len());
        let line = format!("{head}{}];\n", items.join(", "));
        if line.len() <= 101 {
            line
        } else {
            format!("{head}\n    {}\n];\n", items.join(",\n    "))
        }
    };
    let mut s = array("LO", &|r| r.0 as u64);
    s += &array("HI", &|r| r.1 as u64);
    if with_value {
        s += &array("W", &|r| r.2);
    }
    s
}

/// The lookups, in the same module as the tables they read.
const LOOKUP: &str = r#"
// The last run whose first code point is at most `c`, or the run count.
fn width_run(c: u64) -> u64 {
    let mut lo: u64 = 0;
    let mut hi: u64 = {W};
    loop {
        if lo >= hi {
            break;
        }
        let mid = wrapping_add(lo, wrapping_sub(hi, lo) >> 1);
        let first = if mid < {W} {
            WIDTH_LO[mid]
        } else {
            0
        };
        if first <= c {
            lo = wrapping_add(mid, 1);
        } else {
            hi = mid;
        }
    }
    if lo == 0 {
        {W}
    } else {
        wrapping_sub(lo, 1)
    }
}

// `UnicodeWidthChar::width(c).unwrap_or(1)` for the char `c`.
pub fn char_width(c: u64) -> u64 {
    let i = width_run(c);
    if i < {W} {
        if c <= WIDTH_HI[i] {
            WIDTH_W[i]
        } else {
            1
        }
    } else {
        1
    }
}

// `char::is_whitespace` for the char `c`.
pub fn is_space(c: u64) -> bool {
    let mut i: u64 = 0;
    loop {
        if i >= {S} {
            break;
        }
        let lo = if i < {S} {
            SPACE_LO[i]
        } else {
            0
        };
        let hi = if i < {S} {
            SPACE_HI[i]
        } else {
            0
        };
        if c < lo {
            return false;
        }
        if c <= hi {
            return true;
        }
        i = wrapping_add(i, 1);
    }
    false
}
"#;

pub fn generate() -> String {
    let width = runs(|c| c.width().unwrap_or(1) as u64, 1);
    let space = runs(|c| c.is_whitespace() as u64, 0);
    let mut s = String::from(
        "// @generated by crates/vesper-diagnostics/examples/width_table.rs; do not edit.\n\
         // Display widths of chars from unicode-width 0.1.14 (`UnicodeWidthChar::width`,\n\
         // a control character counted as 1 as ariadne does), as the runs of code\n\
         // points whose width is not 1, and the runs of Rust's `char::is_whitespace`.\n\n",
    );
    s += &table("WIDTH", &width, true);
    s += "\n";
    s += &table("SPACE", &space, false);
    // The bounds are literals: a guard `i < N` against a literal is what
    // lets the checker accept the table reads.
    s += &LOOKUP
        .replace("{W}", &width.len().to_string())
        .replace("{S}", &space.len().to_string());
    s
}

#[allow(dead_code)]
fn main() {
    print!("{}", generate());
}
