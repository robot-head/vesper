#[test]
fn miss_then_hit_with_identical_accepted_outputs() {
    let env = Env::new();
    let runner = env.runner();
    let req = env.codegen();

    let first = runner.build(&req, env.path("dest1"), rw()).unwrap();
    assert_eq!(first.cache, CacheStatus::Miss);
    assert!(first.executed && first.newly_recorded);
    assert_eq!(read(&env.path("dest1/generated.vsp")), GENERATED);
    assert_eq!(first.outputs.len(), 1);
    assert_eq!(first.outputs[0].path, "generated.vsp");
    assert_eq!(first.outcome.tokens[0].kind, TokenKind::StringLiteral);
    assert_eq!(first.outcome.tokens[0].text, "/out/generated.vsp");
    assert!(first.fuel_consumed > 0);

    let second = runner.build(&req, env.path("dest2"), rw()).unwrap();
    assert_eq!(second.cache, CacheStatus::Hit);
    assert!(!second.executed && !second.newly_recorded);
    assert_eq!(read(&env.path("dest2/generated.vsp")), GENERATED);
    for (a, b) in [
        (&first.key, &second.key),
        (&first.manifest, &second.manifest),
        (&first.output_tree, &second.output_tree),
    ] {
        assert_eq!(a, b);
    }
    assert_eq!(first.outputs, second.outputs);
    assert_eq!(first.outcome, second.outcome);
    assert_eq!(first.fuel_consumed, second.fuel_consumed);
    assert_eq!(first.stdout, second.stdout);

    // A fresh runner (new process, same store) hits too.
    let third = env.runner().build(&req, env.path("dest3"), rw()).unwrap();
    assert_eq!(third.cache, CacheStatus::Hit);
    assert!(env.scratch_is_empty());
    assert!(runner.store().verify_all().unwrap().is_clean());
}

#[test]
fn workspace_edits_cannot_mutate_stored_artifacts() {
    let env = Env::new();
    let runner = env.runner();
    let req = env.codegen();
    let first = runner.build(&req, env.path("dest1"), rw()).unwrap();
    let blob = file_blob(&runner, &first, "generated.vsp");

    #[cfg(unix)]
    {
        use std::os::unix::fs::MetadataExt;
        let ws = fs::metadata(env.path("dest1/generated.vsp")).unwrap();
        let obj = fs::metadata(runner.store().object_path(&blob)).unwrap();
        assert_ne!(ws.ino(), obj.ino());
        assert_eq!(ws.nlink(), 1);
    }
    fs::write(env.path("dest1/generated.vsp"), "tampered").unwrap();
    fs::write(env.path("dest1/extra"), "x").unwrap();

    assert_eq!(
        runner.store().read_blob(&blob).unwrap(),
        GENERATED.as_bytes()
    );
    let hit = runner.build(&req, env.path("dest2"), rw()).unwrap();
    assert_eq!(hit.cache, CacheStatus::Hit);
    assert_eq!(read(&env.path("dest2/generated.vsp")), GENERATED);
    assert!(!env.path("dest2/extra").exists());
    assert!(runner.store().verify_all().unwrap().is_clean());
}

#[test]
fn every_observable_input_and_configuration_changes_the_key() {
    let env = Env::new();
    let runner = env.runner();
    let base = env.codegen();
    let key = |r: &BuildRequest| runner.prepare(r).unwrap().key();
    let k0 = key(&base);
    assert_eq!(k0, key(&base), "keys are deterministic");

    let mut variants: Vec<(&str, BuildRequest)> = Vec::new();
    let mut v = |name, f: &dyn Fn(&mut BuildRequest)| {
        let mut r = base.clone();
        f(&mut r);
        variants.push((name, r));
    };
    v("component bytes", &|r| r.component = component_variant("a"));
    v("other component bytes", &|r| {
        r.component = component_variant("b")
    });
    v("args", &|r| r.invocation.args[1] = "/out/other.vsp".into());
    v("entry", &|r| r.invocation.entry = "echo".into());
    v("tokens", &|r| {
        r.invocation.tokens = vec![vesper_loom_sandbox::Token {
            kind: TokenKind::Ident,
            text: "x".into(),
            span: vesper_loom_sandbox::transport::Span {
                file: 0,
                start: 0,
                end: 1,
            },
            scopes: vec![],
            pre_resolved: None,
        }]
    });
    v("no target", &|r| r.target = None);
    v("target", &|r| {
        r.target = Some("aarch64-unknown-linux-gnu".into())
    });
    v("option", &|r| {
        r.options.insert("profile".into(), "release".into());
    });
    v("wall clock", &|r| r.determinism.wall_clock_ns = 1);
    v("monotonic", &|r| r.determinism.monotonic_ns = 1);
    v("seed", &|r| r.determinism.random_seed = 1);
    v("fuel", &|r| r.limits.fuel += 1);
    v("memory", &|r| r.limits.max_memory_bytes += 65536);
    v("tables", &|r| r.limits.max_table_elements += 1);
    v("instances", &|r| r.limits.max_instances += 1);
    v("memories", &|r| r.limits.max_memories += 1);
    v("table count", &|r| r.limits.max_tables += 1);
    v("stdio", &|r| r.limits.max_stdio_bytes += 1);
    v("output bytes", &|r| r.limits.max_output_bytes += 1);
    v("output entries", &|r| r.limits.max_output_entries += 1);
    v("backstop", &|r| {
        r.limits.wall_clock_backstop += Duration::from_secs(1)
    });
    v("transport tokens", &|r| r.limits.transport.max_tokens += 1);
    v("transport text", &|r| {
        r.limits.transport.max_text_bytes += 1
    });
    v("transport scopes", &|r| {
        r.limits.transport.max_scopes_per_token += 1
    });
    v("transport total", &|r| {
        r.limits.transport.max_total_scopes += 1
    });
    v("transport diags", &|r| {
        r.limits.transport.max_diagnostics += 1
    });
    v("mount point", &|r| {
        r.inputs[0].guest_path = "/in/schema".into();
        r.invocation.args[0] = "/in/proto/schema.txt".into();
    });

    let mut seen = HashSet::from([k0]);
    for (name, r) in &variants {
        assert!(seen.insert(key(r)), "{name} did not change the key");
    }

    // Input contents: edit, add, rename, executable bit, extra mount.
    let proto = env.path("proto");
    let mut content_key = |f: &dyn Fn()| {
        f();
        let k = key(&base);
        assert!(seen.insert(k), "input change did not change the key");
    };
    content_key(&|| fs::write(proto.join("schema.txt"), "id: u32\n").unwrap());
    content_key(&|| fs::write(proto.join("notes.txt"), "").unwrap());
    content_key(&|| fs::rename(proto.join("notes.txt"), proto.join("notes2.txt")).unwrap());
    #[cfg(unix)]
    content_key(&|| {
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(proto.join("notes2.txt"), fs::Permissions::from_mode(0o755)).unwrap()
    });
    content_key(&|| fs::create_dir(proto.join("sub")).unwrap());
    fs::create_dir(env.path("extra")).unwrap();
    let k = key(&base.clone().with_input("/in/extra", env.path("extra")));
    assert!(seen.insert(k), "an extra mount did not change the key");

    // The host location of an input is not observable and not in the key.
    let before = key(&base);
    let moved = env.path("moved");
    fs::rename(&proto, &moved).unwrap();
    let mut relocated = base.clone();
    relocated.inputs[0].host_path = moved;
    assert_eq!(key(&relocated), before);
}

#[test]
fn same_interface_component_change_misses_and_executes() {
    let env = Env::new();
    let runner = env.runner();
    let base = env.codegen();
    let first = runner.build(&base, env.path("dest1"), rw()).unwrap();

    let mut changed = base.clone();
    changed.component = component_variant("body change");
    let second = runner.build(&changed, env.path("dest2"), rw()).unwrap();
    assert_ne!(first.key, second.key);
    assert_eq!(second.cache, CacheStatus::Miss);
    assert!(second.executed);
    assert_eq!(read(&env.path("dest2/generated.vsp")), GENERATED);
    // Both derivations are recorded independently.
    let again = runner.build(&base, env.path("dest3"), rw()).unwrap();
    assert_eq!(again.cache, CacheStatus::Hit);
    assert_eq!(again.key, first.key);
}

#[test]
fn incompatible_engine_builder_or_host_identities_never_share_results() {
    let env = Env::new();
    let runner = env.runner();
    let req = env.codegen();
    let first = runner.build(&req, env.path("dest0"), rw()).unwrap();
    assert_eq!(first.cache, CacheStatus::Miss);

    let base = ExecutionIdentity::current();
    assert!(base.is_complete(), "missing: {:?}", base.missing());
    let mut seen = HashSet::from([first.key.clone()]);
    type Mutation = Box<dyn Fn(&mut ExecutionIdentity)>;
    let mutations: Vec<(&str, Mutation)> = vec![
        (
            "engine",
            Box::new(|i| i.engine_dependencies = Some("other-wasmtime".into())),
        ),
        (
            "host",
            Box::new(|i| i.host_target = Some("aarch64-apple-darwin".into())),
        ),
        (
            "builder",
            Box::new(|i| i.builder_source = Some("patched".into())),
        ),
        (
            "builder version",
            Box::new(|i| i.builder_version = "0.2.0".into()),
        ),
        (
            "sandbox",
            Box::new(|i| i.sandbox_source = Some("patched".into())),
        ),
        ("cas", Box::new(|i| i.cas_source = Some("patched".into()))),
        ("rustc", Box::new(|i| i.rustc = Some("rustc 9.9.9".into()))),
        ("wit", Box::new(|i| i.wit_digest = "0".repeat(64))),
        ("protocol", Box::new(|i| i.protocol_version = 2)),
    ];
    for (n, (name, mutate)) in mutations.iter().enumerate() {
        let mut id = base.clone();
        mutate(&mut id);
        let other = env.runner().with_identity_unchecked(id);
        let out = other
            .build(&req, env.path(&format!("dest{}", n + 1)), rw())
            .unwrap();
        assert_eq!(out.cache, CacheStatus::Miss, "{name} reused a result");
        assert!(out.executed);
        assert!(seen.insert(out.key), "{name} did not change the key");
    }
}

#[test]
fn unknown_fingerprint_refuses_reusable_results() {
    let env = Env::new();
    let mut id = ExecutionIdentity::current();
    id.engine_dependencies = None;
    id.sandbox_source = None;
    let runner = env.runner().with_identity_unchecked(id);
    let req = env.codegen();
    for cache in [CachePolicy::ReadWrite, CachePolicy::Verify] {
        let opts = RunOptions {
            cache,
            ..RunOptions::default()
        };
        match runner.build(&req, env.path("dest"), opts).unwrap_err() {
            BuildError::UnknownFingerprint { missing } => {
                assert_eq!(missing, vec!["sandbox_source", "engine_dependencies"]);
            }
            other => panic!("{other:?}"),
        }
    }
    assert!(!env.path("dest").exists());

    let opts = RunOptions {
        cache: CachePolicy::Uncached,
        ..RunOptions::default()
    };
    let out = runner.build(&req, env.path("dest"), opts).unwrap();
    assert_eq!(out.cache, CacheStatus::Uncached);
    assert!(!out.newly_recorded);
    assert_eq!(read(&env.path("dest/generated.vsp")), GENERATED);
    let prepared = runner.prepare(&req).unwrap();
    assert_eq!(recorded(&runner, &prepared), None);
    assert_eq!(runner.store().verify_all().unwrap().verified_derivations, 0);
}

#[test]
fn mutating_the_original_after_snapshot_does_not_affect_execution() {
    let env = Env::new();
    let runner = env.runner();
    let prepared = runner.prepare(&env.codegen()).unwrap();
    let snapshot = prepared.snapshots()[0].1;

    fs::write(env.path("proto/schema.txt"), "evil: Injected\n").unwrap();
    fs::write(env.path("proto/added.txt"), "late").unwrap();

    let out = runner.execute(&prepared, env.path("dest"), rw()).unwrap();
    assert_eq!(out.cache, CacheStatus::Miss);
    assert_eq!(read(&env.path("dest/generated.vsp")), GENERATED);
    let tree = runner.store().read_tree(&snapshot).unwrap();
    assert!(tree.get("added.txt").is_none());

    // A new preparation sees the new contents and so a new key.
    let fresh = runner.prepare(&env.codegen()).unwrap();
    assert_ne!(fresh.key(), prepared.key());
    let out = runner.execute(&fresh, env.path("dest2"), rw()).unwrap();
    assert_eq!(out.cache, CacheStatus::Miss);
    assert!(read(&env.path("dest2/generated.vsp")).contains("evil: Injected"));
}

