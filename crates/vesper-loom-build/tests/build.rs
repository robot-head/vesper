const COMPONENT: &[u8] =
    include_bytes!("../../vesper-loom-sandbox/fixtures/bin/step.component.wasm");
const PREVIEW1: &[u8] = include_bytes!("../../vesper-loom-sandbox/fixtures/bin/step.preview1.wasm");
const SUMS: &str = include_str!("../../vesper-loom-sandbox/fixtures/bin/SHA256SUMS");

const SCHEMA: &str = "id: u64\nname: Str\n";
const GENERATED: &str =
    "// generated by vesper-sandbox-fixture\nstruct Generated {\n    id: u64,\n    name: Str,\n}\n";

fn engine() -> Arc<BuildEngine> {
    static ENGINE: OnceLock<Arc<BuildEngine>> = OnceLock::new();
    ENGINE
        .get_or_init(|| Arc::new(BuildEngine::new().unwrap()))
        .clone()
}

/// root/proto/schema.txt, root/store, root/scratch, destinations under root.
struct Env {
    root: tempfile::TempDir,
}

impl Env {
    fn new() -> Self {
        let root = tempfile::tempdir().unwrap();
        fs::create_dir(root.path().join("proto")).unwrap();
        fs::write(root.path().join("proto/schema.txt"), SCHEMA).unwrap();
        Env { root }
    }

    fn path(&self, rel: &str) -> PathBuf {
        self.root.path().join(rel)
    }

    fn runner(&self) -> Runner {
        Runner::open(engine(), self.path("store"), self.path("scratch")).unwrap()
    }

    fn codegen(&self) -> BuildRequest {
        BuildRequest::build_script(COMPONENT.to_vec(), "codegen")
            .with_input("/in/proto", self.path("proto"))
            .with_args(["/in/proto/schema.txt", "/out/generated.vsp"])
            .with_target("x86_64-unknown-linux-gnu")
    }

    fn step(&self, entry: &str, args: &[&str]) -> BuildRequest {
        BuildRequest::build_script(COMPONENT.to_vec(), entry)
            .with_input("/in/proto", self.path("proto"))
            .with_args(args.iter().copied())
    }

    fn scratch_is_empty(&self) -> bool {
        fs::read_dir(self.path("scratch")).unwrap().next().is_none()
    }
}

fn read(path: &Path) -> String {
    fs::read_to_string(path).unwrap()
}

fn sandbox(e: &BuildError) -> Option<&SandboxError> {
    match e {
        BuildError::Sandbox(s) => Some(s),
        _ => None,
    }
}

fn rw() -> RunOptions {
    RunOptions::default()
}

fn replace() -> RunOptions {
    RunOptions {
        destination: DestinationPolicy::Replace,
        ..RunOptions::default()
    }
}

/// The same component with an extra custom section appended: identical
/// WIT interface and behavior, different implementation bytes.
fn component_variant(tag: &str) -> Vec<u8> {
    fn leb(mut n: usize, out: &mut Vec<u8>) {
        loop {
            let byte = (n & 0x7f) as u8;
            n >>= 7;
            if n == 0 {
                out.push(byte);
                return;
            }
            out.push(byte | 0x80);
        }
    }
    let name = b"vesper-test";
    let mut body = Vec::new();
    leb(name.len(), &mut body);
    body.extend_from_slice(name);
    body.extend_from_slice(tag.as_bytes());
    let mut bytes = COMPONENT.to_vec();
    bytes.push(0);
    leb(body.len(), &mut bytes);
    bytes.extend_from_slice(&body);
    bytes
}

fn file_blob(runner: &Runner, outcome: &BuildOutcome, name: &str) -> ObjectId {
    let tree = runner
        .store()
        .read_tree(&outcome.output_tree.parse().unwrap())
        .unwrap();
    let entry = tree.get(name).unwrap();
    assert!(matches!(entry.kind, EntryKind::File { .. }));
    tree.child_id(entry)
}

fn make_writable(path: &Path) {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(path, fs::Permissions::from_mode(0o644)).unwrap();
    }
    #[cfg(not(unix))]
    {
        let mut p = fs::metadata(path).unwrap().permissions();
        #[allow(clippy::permissions_set_readonly_false)]
        p.set_readonly(false);
        fs::set_permissions(path, p).unwrap();
    }
}

fn record_path(runner: &Runner, prepared: &PreparedBuild) -> PathBuf {
    let hex = prepared.key().0.to_hex();
    runner
        .store()
        .root()
        .join("derivations/v1")
        .join(&hex[..2])
        .join(hex)
}

fn recorded(runner: &Runner, prepared: &PreparedBuild) -> Option<ObjectId> {
    runner
        .store()
        .lookup_derivation(prepared.derivation_inputs())
        .unwrap()
}

