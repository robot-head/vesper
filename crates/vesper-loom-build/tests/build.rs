#[test]
fn a_prepared_build_runs_only_under_the_identity_that_keyed_it() {
    let env = Env::new();
    let prepared = env.runner().prepare(&env.codegen()).unwrap();
    for mutate in [
        (|i: &mut ExecutionIdentity| i.host_target = Some("aarch64-apple-darwin".into()))
            as fn(&mut ExecutionIdentity),
        |i| i.engine_dependencies = None,
    ] {
        let mut id = ExecutionIdentity::current();
        mutate(&mut id);
        let other = env.runner().with_identity_unchecked(id);
        for cache in [CachePolicy::ReadWrite, CachePolicy::Uncached] {
            let opts = RunOptions {
                cache,
                ..RunOptions::default()
            };
            let err = other
                .execute(&prepared, env.path("dest"), opts)
                .unwrap_err();
            assert!(matches!(err, BuildError::IdentityMismatch), "{err:?}");
        }
    }
    // Prepared with an incomplete identity, it cannot be recorded by a
    // complete runner either.
    let mut id = ExecutionIdentity::current();
    id.rustc = None;
    let incomplete = env.runner().with_identity_unchecked(id);
    let prepared = incomplete.prepare(&env.codegen()).unwrap();
    let err = env
        .runner()
        .execute(&prepared, env.path("dest"), rw())
        .unwrap_err();
    assert!(matches!(err, BuildError::IdentityMismatch), "{err:?}");
    assert!(!env.path("dest").exists());
    assert_eq!(recorded(&env.runner(), &prepared), None);
}

#[test]
fn inputs_are_read_only_and_ambient_authority_is_denied() {
    let env = Env::new();
    let runner = env.runner();
    let original = env.path("proto/schema.txt");

    // Writes into an input mount fail inside the guest; nothing is published.
    let req = env.step("write", &["/in/proto/schema.txt", "overwritten"]);
    let prepared = runner.prepare(&req).unwrap();
    match runner.execute(&prepared, env.path("d1"), rw()).unwrap_err() {
        BuildError::GuestFailed { diagnostics } => {
            assert!(
                diagnostics[0]
                    .message
                    .contains("write /in/proto/schema.txt")
            );
        }
        other => panic!("{other:?}"),
    }
    assert_eq!(read(&original), SCHEMA);
    assert_eq!(recorded(&runner, &prepared), None);
    assert!(!env.path("d1").exists());

    // The host path of the original input is not reachable.
    let host = original.to_str().unwrap().to_owned();
    let err = runner
        .build(&env.step("read", &[&host]), env.path("d2"), rw())
        .unwrap_err();
    assert!(matches!(err, BuildError::GuestFailed { .. }), "{err:?}");

    // Exactly the declared mount and /out; no environment or arguments.
    let out = runner
        .build(&env.step("authority", &[]), env.path("d3"), rw())
        .unwrap();
    let seen: Vec<&str> = out.outcome.tokens.iter().map(|t| t.text.as_str()).collect();
    assert!(seen.contains(&"preopen:/in/proto"), "{seen:?}");
    assert!(seen.contains(&"preopen:/out"), "{seen:?}");
    assert!(seen.contains(&"std-env-count:0"), "{seen:?}");
    assert_eq!(seen.iter().filter(|s| s.starts_with("preopen:")).count(), 2);
    assert!(
        !seen
            .iter()
            .any(|s| s.starts_with("env:") || s.starts_with("arg:"))
    );

    // The mount shows the snapshot's contents only.
    let out = runner
        .build(&env.step("list-dir", &["/in/proto"]), env.path("d4"), rw())
        .unwrap();
    let names: Vec<&str> = out.outcome.tokens.iter().map(|t| t.text.as_str()).collect();
    assert_eq!(names, ["schema.txt"]);

    // Network denial is observable and still accepted as the guest's
    // own (error) result: nothing is published.
    let err = runner
        .build(&env.step("dns", &["example.com"]), env.path("d5"), rw())
        .unwrap_err();
    assert!(matches!(err, BuildError::GuestFailed { .. }), "{err:?}");
}

#[test]
fn failures_publish_nothing_and_preserve_the_destination() {
    let env = Env::new();
    let runner = env.runner();
    let dest = env.path("dest");
    fs::create_dir(&dest).unwrap();
    fs::write(dest.join("keep.txt"), "previous good output").unwrap();

    type Check = fn(&BuildError) -> bool;
    let cases: Vec<(&str, BuildRequest, Check)> = vec![
        ("panic", env.step("panic", &[]), |e| {
            matches!(sandbox(e), Some(SandboxError::Trap { .. }))
        }),
        (
            "fuel",
            {
                let mut r = env.step("spin", &[]);
                r.limits.fuel = 5_000_000;
                r
            },
            |e| matches!(sandbox(e), Some(SandboxError::FuelExhausted { .. })),
        ),
        (
            "memory",
            {
                let mut r = env.step("alloc", &[]);
                r.limits.max_memory_bytes = 16 << 20;
                r.limits.fuel = u64::MAX / 2;
                r
            },
            |e| matches!(sandbox(e), Some(SandboxError::MemoryLimitExceeded { .. })),
        ),
        (
            "timeout",
            {
                let mut r = env.step("sleep", &["3600"]);
                r.limits.wall_clock_backstop = Duration::from_millis(300);
                r
            },
            |e| matches!(sandbox(e), Some(SandboxError::WallClockTimeout { .. })),
        ),
        (
            "stdio",
            {
                let mut r = env.step("stdout-flood", &[]);
                r.limits.max_stdio_bytes = 8 << 10;
                r
            },
            |e| matches!(sandbox(e), Some(SandboxError::Trap { .. })),
        ),
        (
            "output bytes",
            {
                let mut r = env.codegen();
                r.limits.max_output_bytes = 4;
                r
            },
            |e| matches!(sandbox(e), Some(SandboxError::Output(_))),
        ),
        ("guest error", env.step("no-such-entry", &[]), |e| {
            matches!(e, BuildError::GuestFailed { .. })
        }),
        (
            "bad schema",
            {
                fs::create_dir(env.path("bad")).unwrap();
                fs::write(env.path("bad/schema.txt"), "no colon here\n").unwrap();
                let mut r = env.codegen();
                r.inputs[0].host_path = env.path("bad");
                r
            },
            |e| matches!(e, BuildError::GuestFailed { .. }),
        ),
    ];
    for (name, req, check) in cases {
        let prepared = runner.prepare(&req).unwrap();
        let err = runner.execute(&prepared, &dest, replace()).unwrap_err();
        assert!(check(&err), "{name}: {err:?}");
        assert_eq!(recorded(&runner, &prepared), None, "{name} published");
        assert_eq!(
            fs::read_dir(&dest).unwrap().count(),
            1,
            "{name} touched the destination"
        );
        assert_eq!(read(&dest.join("keep.txt")), "previous good output");
        assert!(env.scratch_is_empty(), "{name} left scratch state");
    }
    assert_eq!(runner.store().verify_all().unwrap().verified_derivations, 0);

    // A later success replaces it atomically and leaves no staging behind.
    let out = runner.build(&env.codegen(), &dest, replace()).unwrap();
    assert_eq!(out.cache, CacheStatus::Miss);
    assert!(!dest.join("keep.txt").exists());
    assert_eq!(read(&dest.join("generated.vsp")), GENERATED);
    let leftovers: Vec<_> = fs::read_dir(env.root.path())
        .unwrap()
        .flatten()
        .filter(|e| e.file_name().to_string_lossy().starts_with(".vlb-"))
        .collect();
    assert!(leftovers.is_empty(), "{leftovers:?}");
}

#[test]
fn create_new_refuses_an_existing_destination_before_executing() {
    let env = Env::new();
    let runner = env.runner();
    fs::create_dir(env.path("dest")).unwrap();
    let prepared = runner.prepare(&env.codegen()).unwrap();
    let err = runner
        .execute(&prepared, env.path("dest"), rw())
        .unwrap_err();
    assert!(matches!(err, BuildError::Destination { .. }), "{err:?}");
    assert_eq!(recorded(&runner, &prepared), None);

    // Replace is limited to directories.
    fs::write(env.path("file"), "x").unwrap();
    let err = runner
        .execute(&prepared, env.path("file"), replace())
        .unwrap_err();
    assert!(matches!(err, BuildError::Destination { .. }), "{err:?}");
    assert_eq!(read(&env.path("file")), "x");

    // Replacing an ancestor of the store or scratch area would delete it.
    let err = runner
        .execute(&prepared, env.root.path(), replace())
        .unwrap_err();
    assert!(
        matches!(
            err,
            BuildError::Destination { .. }
                | BuildError::Request(RequestError::LayoutOverlap { .. })
        ),
        "{err:?}"
    );
    fs::create_dir(env.path("cache")).unwrap();
    let nested =
        Runner::open(engine(), env.path("cache/store"), env.path("cache/scratch")).unwrap();
    let prepared_nested = nested.prepare(&env.codegen()).unwrap();
    let err = nested
        .execute(&prepared_nested, env.path("cache"), replace())
        .unwrap_err();
    assert!(matches!(err, BuildError::Destination { .. }), "{err:?}");
    assert!(nested.store().verify_all().unwrap().is_clean());
    assert!(env.path("cache/store").is_dir());

    // Destinations inside an input or the store are refused.
    for bad in ["proto/gen", "store/gen", "scratch/gen"] {
        let err = runner.execute(&prepared, env.path(bad), rw()).unwrap_err();
        assert!(
            matches!(
                err,
                BuildError::Destination { .. }
                    | BuildError::Request(RequestError::LayoutOverlap { .. })
            ),
            "{bad}: {err:?}"
        );
    }
}

#[test]
fn concurrent_writers_of_one_key_agree() {
    let env = Env::new();
    let req = env.codegen();
    let results: Vec<BuildOutcome> = std::thread::scope(|s| {
        let handles: Vec<_> = (0..6)
            .map(|i| {
                let env = &env;
                let req = &req;
                s.spawn(move || {
                    env.runner()
                        .build(req, env.path(&format!("dest{i}")), rw())
                        .unwrap()
                })
            })
            .collect();
        handles.into_iter().map(|h| h.join().unwrap()).collect()
    });
    assert_eq!(results.iter().filter(|r| r.newly_recorded).count(), 1);
    for r in &results {
        assert_eq!(r.manifest, results[0].manifest);
        assert_eq!(r.output_tree, results[0].output_tree);
        assert!(matches!(r.cache, CacheStatus::Miss | CacheStatus::Hit));
    }
    for i in 0..6 {
        assert_eq!(
            read(&env.path(&format!("dest{i}/generated.vsp"))),
            GENERATED
        );
    }
    let report = env.runner().store().verify_all().unwrap();
    assert!(report.is_clean(), "{report:?}");
    assert_eq!(report.verified_derivations, 1);
}

#[test]
fn divergent_results_for_one_key_are_detected_not_overwritten() {
    let env = Env::new();
    let runner = env.runner();
    let req = env.codegen();
    let prepared = runner.prepare(&req).unwrap();

    // Forge a well-formed result for this key from a different build.
    let mut other = env.step("write", &["/out/generated.vsp", "something else"]);
    other.inputs.clear();
    let foreign = runner.build(&other, env.path("foreign"), rw()).unwrap();
    let id: ObjectId = foreign.manifest.parse().unwrap();
    let mut m = ResultManifest::decode(&runner.store().read_blob(&id).unwrap()).unwrap();
    m.key = prepared.key().to_string();
    let forged = runner
        .store()
        .put_blob(Domain::Artifact, &m.encode())
        .unwrap()
        .id;
    runner
        .store()
        .publish_derivation(prepared.derivation_inputs(), forged)
        .unwrap();

    // Verify re-executes and refuses to accept or overwrite.
    let verify = RunOptions {
        cache: CachePolicy::Verify,
        ..RunOptions::default()
    };
    match runner
        .execute(&prepared, env.path("dest"), verify)
        .unwrap_err()
    {
        BuildError::DivergentOutput {
            existing, proposed, ..
        } => {
            assert_eq!(existing, forged);
            assert_ne!(proposed, forged);
        }
        other => panic!("{other:?}"),
    }
    assert!(!env.path("dest").exists());
    assert_eq!(recorded(&runner, &prepared), Some(forged));

    // A verified run of an honest record matches.
    let env2 = Env::new();
    let runner2 = env2.runner();
    runner2
        .build(&env2.codegen(), env2.path("a"), rw())
        .unwrap();
    let out = runner2
        .build(&env2.codegen(), env2.path("b"), verify)
        .unwrap();
    assert_eq!(out.cache, CacheStatus::Verified);
    assert!(out.executed && !out.newly_recorded);
}

#[test]
fn corrupt_and_dangling_cache_entries_are_explicit() {
    let env = Env::new();
    let runner = env.runner();
    let req = env.codegen();
    let prepared = runner.prepare(&req).unwrap();
    let first = runner.execute(&prepared, env.path("d0"), rw()).unwrap();
    let rebuild = RunOptions {
        on_corrupt: CorruptionPolicy::Rebuild,
        ..RunOptions::default()
    };

    // 1. A corrupted output object.
    let blob = file_blob(&runner, &first, "generated.vsp");
    let path = runner.store().object_path(&blob);
    make_writable(&path);
    fs::write(&path, "struct Evil {}\n").unwrap();
    let err = runner.execute(&prepared, env.path("d1"), rw()).unwrap_err();
    assert!(matches!(err, BuildError::CorruptCache { .. }), "{err:?}");
    assert!(!env.path("d1").exists());
    let out = runner.execute(&prepared, env.path("d1"), rebuild).unwrap();
    assert_eq!(out.cache, CacheStatus::Repaired);
    assert_eq!(out.manifest, first.manifest);
    assert_eq!(read(&env.path("d1/generated.vsp")), GENERATED);
    assert!(runner.store().verify_all().unwrap().is_clean());

    // 2. A dangling record: its manifest object is gone.
    let manifest: ObjectId = first.manifest.parse().unwrap();
    fs::remove_file(runner.store().object_path(&manifest)).unwrap();
    let err = runner.execute(&prepared, env.path("d2"), rw()).unwrap_err();
    assert!(matches!(err, BuildError::CorruptCache { .. }), "{err:?}");
    let out = runner.execute(&prepared, env.path("d2"), rebuild).unwrap();
    assert_eq!(out.cache, CacheStatus::Repaired);
    assert_eq!(out.manifest, first.manifest);

    // 3. A corrupt derivation record.
    let record = record_path(&runner, &prepared);
    make_writable(&record);
    fs::write(&record, b"garbage").unwrap();
    let err = runner.execute(&prepared, env.path("d3"), rw()).unwrap_err();
    assert!(matches!(err, BuildError::CorruptCache { .. }), "{err:?}");
    let out = runner.execute(&prepared, env.path("d3"), rebuild).unwrap();
    assert_eq!(out.cache, CacheStatus::Repaired);
    let hit = runner.execute(&prepared, env.path("d4"), rw()).unwrap();
    assert_eq!(hit.cache, CacheStatus::Hit);
    assert!(runner.store().verify_all().unwrap().is_clean());

    // 4. A record naming a manifest for another key is not a hit.
    let other = runner.prepare(&env.step("echo", &[])).unwrap();
    runner
        .store()
        .publish_derivation(other.derivation_inputs(), manifest)
        .unwrap();
    let err = runner.execute(&other, env.path("d5"), rw()).unwrap_err();
    match err {
        BuildError::CorruptCache { reason, .. } => assert!(reason.contains("belongs to")),
        other => panic!("{other:?}"),
    }
}

#[test]
fn invalid_requests_are_rejected_before_any_execution() {
    let env = Env::new();
    let runner = env.runner();
    let base = env.codegen();
    let expect = |r: BuildRequest, check: fn(&RequestError) -> bool| {
        match runner.build(&r, env.path("dest"), rw()) {
            Err(BuildError::Request(e)) => assert!(check(&e), "{e:?}"),
            other => panic!("{other:?}"),
        }
        assert!(!env.path("dest").exists());
    };
    let with = |f: &dyn Fn(&mut BuildRequest)| {
        let mut r = base.clone();
        f(&mut r);
        r
    };
    expect(with(&|r| r.version = 2), |e| {
        matches!(e, RequestError::UnsupportedVersion { found: 2, .. })
    });
    expect(with(&|r| r.invocation.protocol_version = 9), |e| {
        matches!(e, RequestError::UnsupportedProtocol { .. })
    });
    expect(with(&|r| r.invocation.step = StepKind::ProcMacro), |e| {
        matches!(e, RequestError::UnsupportedStep(StepKind::ProcMacro))
    });
    expect(with(&|r| r.invocation.step = StepKind::DeriveMacro), |e| {
        matches!(e, RequestError::UnsupportedStep(StepKind::DeriveMacro))
    });
    expect(with(&|r| r.network = NetworkPolicy::Allowed), |e| {
        matches!(e, RequestError::IncompatiblePolicy(_))
    });
    expect(with(&|r| r.component = PREVIEW1.to_vec()), |e| {
        matches!(e, RequestError::NotAComponent(_))
    });
    expect(with(&|r| r.component = b"not wasm".to_vec()), |e| {
        matches!(e, RequestError::NotAComponent(_))
    });
    expect(with(&|r| r.invocation.args.push("bad\narg".into())), |e| {
        matches!(e, RequestError::Malformed { .. })
    });
    expect(with(&|r| r.limits.fuel = 0), |e| {
        matches!(e, RequestError::ZeroLimit("fuel"))
    });
    for bad in ["in", "/", "/in/../x", "/in//x", "/in/"] {
        let r = with(&|r| r.inputs[0].guest_path = bad.into());
        expect(r, |e| matches!(e, RequestError::InvalidGuestPath(_)));
    }
    expect(with(&|r| r.inputs[0].guest_path = "/out/x".into()), |e| {
        matches!(e, RequestError::MountOverlapsOutput(_))
    });
    fs::create_dir(env.path("other")).unwrap();
    let other = env.path("other");
    expect(base.clone().with_input("/in/proto", &other), |e| {
        matches!(e, RequestError::OverlappingMounts { .. })
    });
    expect(base.clone().with_input("/in/proto/sub", &other), |e| {
        matches!(e, RequestError::OverlappingMounts { .. })
    });
    expect(
        base.clone().with_input("/in/again", env.path("proto")),
        |e| matches!(e, RequestError::OverlappingHostInputs { .. }),
    );
    expect(
        with(&|r| r.inputs[0].host_path = env.path("missing")),
        |e| matches!(e, RequestError::InputUnavailable { .. }),
    );
    expect(
        with(&|r| r.inputs[0].host_path = env.path("proto/schema.txt")),
        |e| matches!(e, RequestError::InputNotDirectory(_)),
    );
    expect(
        with(&|r| r.inputs[0].host_path = env.root.path().to_owned()),
        |e| matches!(e, RequestError::LayoutOverlap { .. }),
    );

    // Unsupported input contents fail the snapshot, not the build.
    #[cfg(unix)]
    {
        std::os::unix::fs::symlink("../secret", env.path("other/escape")).unwrap();
        let r = with(&|r| r.inputs[0].host_path = env.path("other"));
        match runner.build(&r, env.path("dest"), rw()) {
            Err(BuildError::Snapshot { guest_path, .. }) => assert_eq!(guest_path, "/in/proto"),
            other => panic!("{other:?}"),
        }
    }
    assert_eq!(runner.store().verify_all().unwrap().verified_derivations, 0);
    assert!(env.scratch_is_empty());
}

#[test]
fn request_files_are_versioned_and_strict() {
    let env = Env::new();
    fs::write(env.path("step.wasm"), COMPONENT).unwrap();
    let good = r#"{
        "version": 1,
        "component": "step.wasm",
        "entry": "codegen",
        "args": ["/in/proto/schema.txt", "/out/generated.vsp"],
        "inputs": [{ "guest_path": "/in/proto", "host_path": "proto" }],
        "limits": { "fuel": 40000000, "wall_clock_backstop_ms": 10000 }
    }"#;
    let path = env.path("request.json");
    fs::write(&path, good).unwrap();
    let req = RequestFile::load(&path).unwrap();
    assert_eq!(req.component, COMPONENT);
    assert_eq!(req.inputs[0].host_path, env.path("proto"));
    assert_eq!(req.limits.fuel, 40_000_000);
    assert_eq!(req.limits.wall_clock_backstop, Duration::from_secs(10));
    let out = env.runner().build(&req, env.path("dest"), rw()).unwrap();
    assert_eq!(read(&env.path("dest/generated.vsp")), GENERATED);
    assert_eq!(out.cache, CacheStatus::Miss);

    // A future version is reported as such even with unknown fields.
    let future = good.replace("\"version\": 1", "\"version\": 2, \"new_field\": true");
    assert!(matches!(
        RequestFile::parse(&future),
        Err(RequestError::UnsupportedVersion { found: 2, .. })
    ));
    let unknown = good.replace("\"entry\"", "\"surprise\": 1, \"entry\"");
    assert!(matches!(
        RequestFile::parse(&unknown),
        Err(RequestError::Json(_))
    ));
    let unknown_limit = good.replace("\"fuel\"", "\"disk_quota\": 1, \"fuel\"");
    assert!(matches!(
        RequestFile::parse(&unknown_limit),
        Err(RequestError::Json(_))
    ));
    assert!(matches!(
        RequestFile::parse(r#"{"component": "x"}"#),
        Err(RequestError::Json(_))
    ));
    let mac = good.replace("\"entry\"", "\"step\": \"proc-macro\", \"entry\"");
    fs::write(&path, mac).unwrap();
    let req = RequestFile::load(&path).unwrap();
    assert!(matches!(
        req.validate(),
        Err(RequestError::UnsupportedStep(StepKind::ProcMacro))
    ));
}

