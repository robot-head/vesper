#!/usr/bin/env python3
"""Regenerates vesper/src/huffman_codes.ves and vesper/src/static_table.ves
from the committed Rust tables (src/qpack/huffman_table.rs and
src/qpack/static_table.rs), so the Vesper port and the Rust build read the
same RFC data.

Usage: python3 vesper/gen_tables.py   (from crates/vesper-prism-h3)
Then run `vesper fmt` on both files.
"""
import re

static = open("src/qpack/static_table.rs").read()
rows = re.findall(r'\(\s*b"([^"]*)",\s*b"([^"]*)",?\s*\)', static)
assert len(rows) == 99, len(rows)

huff = open("src/qpack/huffman_table.rs").read()
codes = [(int(n), int(c, 16)) for n, c in re.findall(r"\((\d+), 0x([0-9a-f]+)\)", huff)]
assert len(codes) == 257, len(codes)

out = [
    "// Generated by vesper/gen_tables.py from src/qpack/huffman_table.rs.",
    "// Do not edit by hand.",
    "",
    "// The HPACK Huffman code (RFC 7541 Appendix B): `bit length << 32 | code`",
    "// per symbol, symbol 256 being EOS.",
    "pub fn huffman_codes() -> ChunkSeq[u64] {",
    "    let mut c = ChunkSeq::with_capacity[u64](257);",
]
out += [f"    c.push({(l << 32) | v});" for l, v in codes]
out += ["    c", "}", ""]
open("vesper/src/huffman_codes.ves", "w").write("\n".join(out))

out = [
    "// Generated by vesper/gen_tables.py from src/qpack/static_table.rs.",
    "// Do not edit by hand.",
    "",
    "// The QPACK static table (RFC 9204 Appendix A): the names and values",
    "// concatenated, and the end of each name and value (two per index).",
    "pub fn static_bytes() -> ChunkSeq[u8] {",
    "    let mut b = ChunkSeq::with_capacity[u8](%d);" % sum(len(n) + len(v) for n, v in rows),
]
for n, v in rows:
    out.append(f'    b.extend(in "{n}".as_bytes());')
    if v:
        out.append(f'    b.extend(in "{v}".as_bytes());')
out += ["    b", "}", "", "pub fn static_ends() -> ChunkSeq[u64] {"]
out.append("    let mut e = ChunkSeq::with_capacity[u64](198);")
at = 0
for n, v in rows:
    at += len(n)
    out.append(f"    e.push({at});")
    at += len(v)
    out.append(f"    e.push({at});")
out += ["    e", "}", ""]
open("vesper/src/static_table.ves", "w").write("\n".join(out))
