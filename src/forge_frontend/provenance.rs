//! Macro provenance (REVIEW-STATUS COMP-03). Every function of a checked
//! expanded artifact records whether, and through which macro invocations, it
//! contains expanded code. The table is bound to the original and expanded
//! source hashes by a digest, travels with diagnostics, the IR and Lean
//! extraction, and is what `vesper proof-audit --macro-provenance` checks
//! before it admits a theorem that depends on expanded definitions.
//!
//! Provenance is evidence about where code came from; it never grants
//! authority. Only the fully checked expanded artifact carries semantics.
use super::{ByteRange, MapKind, SourceMapSegment};
use crate::ast::{Diagnostic, Span};
use serde::{Deserialize, Serialize};
use std::collections::{BTreeMap, BTreeSet};
use vesper_lean_syntax::{Declaration, Definition, DefinitionKind, Ident, Term};

pub const SCHEMA: &str = "vesper.forge.provenance/1";
/// Suffix of the Lean marker constant emitted beside each extracted function
/// that contains expanded code: `f$macro_provenance : String := "<digest>"`.
pub const MARKER_SUFFIX: &str = "$macro_provenance";
/// Module-level marker whose value is the whole table's digest.
pub const MODULE_MARKER: &str = "vesper$macro_provenance";

/// One macro invocation and the expanded byte ranges it generated.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ExpansionRecord {
    pub ordinal: u32,
    pub r#macro: String,
    /// The invocation `m!(..)` in the original source.
    pub invocation: ByteRange,
    pub host_function: String,
    /// Expanded-source ranges whose tokens were generated by this expansion.
    pub generated: Vec<ByteRange>,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum FunctionOrigin {
    /// The function body is ordinary source; no macro contributed to it.
    Source,
    /// At least one macro invocation was expanded into the function body.
    Expanded,
}

/// Provenance of one IR (and Lean-extracted) function.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct FunctionProvenance {
    pub function: String,
    pub origin: FunctionOrigin,
    /// Ordinals of the expansions in this function, ascending.
    pub expansions: Vec<u32>,
    /// BLAKE3 over the function's canonical record, its expansion records and
    /// both source hashes. This is the value of the Lean marker constant.
    pub digest: String,
}

/// Whole-artifact provenance table.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ProvenanceTable {
    pub schema: String,
    pub package: String,
    pub source_blake3: String,
    pub expanded_blake3: String,
    pub expansions: Vec<ExpansionRecord>,
    pub functions: Vec<FunctionProvenance>,
    /// BLAKE3 over the canonical table with an empty `digest`.
    pub digest: String,
}

/// Where a diagnostic about expanded code came from in the original source.
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct DiagnosticOrigin {
    /// Span of the diagnostic in the expanded source.
    pub expanded: ByteRange,
    /// Original span: the source token itself, or the invocation that
    /// generated the code.
    pub original: ByteRange,
    pub kind: MapKind,
    /// The macro that generated the code, when `kind` is `generated`.
    pub r#macro: Option<String>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ProvenanceError {
    /// A function, expansion or generated range has no complete record.
    Incomplete(String),
    /// A digest or hash does not match the content it claims to bind.
    Mismatch(String),
    Schema,
}
impl std::fmt::Display for ProvenanceError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Incomplete(what) => write!(f, "macro provenance incomplete: {what}"),
            Self::Mismatch(what) => write!(f, "macro provenance mismatch: {what}"),
            Self::Schema => write!(f, "unsupported macro provenance schema"),
        }
    }
}
impl std::error::Error for ProvenanceError {}

/// One expansion as the expander saw it, before ordinals are assigned.
pub(crate) struct ExpansionInput<'a> {
    pub r#macro: &'a str,
    pub invocation: &'a Span,
    pub host_function: &'a str,
    pub generated: Vec<ByteRange>,
}

fn hex(bytes: [u8; 32]) -> String {
    blake3::Hash::from_bytes(bytes).to_hex().to_string()
}

fn canonical_digest(value: &impl Serialize) -> String {
    // serde_json emits struct fields in declaration order and the tables use
    // only ordered collections, so this encoding is canonical.
    let bytes = serde_json::to_vec(value).expect("provenance records serialize");
    let mut hasher = blake3::Hasher::new();
    hasher.update(SCHEMA.as_bytes());
    hasher.update(&[0]);
    hasher.update(&bytes);
    hasher.finalize().to_hex().to_string()
}

#[derive(Serialize)]
struct FunctionDigestInput<'a> {
    source_blake3: &'a str,
    expanded_blake3: &'a str,
    function: &'a str,
    origin: FunctionOrigin,
    expansions: Vec<&'a ExpansionRecord>,
}

fn function_digest(
    source_blake3: &str,
    expanded_blake3: &str,
    function: &str,
    origin: FunctionOrigin,
    records: &[&ExpansionRecord],
) -> String {
    canonical_digest(&FunctionDigestInput {
        source_blake3,
        expanded_blake3,
        function,
        origin,
        expansions: records.to_vec(),
    })
}

fn within(range: &ByteRange, text: &str) -> bool {
    range.start <= range.end && text.get(range.start..range.end).is_some()
}

impl ProvenanceTable {
    /// Build and validate the table for an expanded artifact. `functions` are
    /// the IR function names and `source_functions` the top-level functions
    /// of the checked expanded module. Fails closed: an IR function that is
    /// not a source function, or an expansion whose host is missing, is an
    /// error rather than an unattributed entry.
    pub(crate) fn build(
        package: &str,
        original: &str,
        expanded: &str,
        expansions: Vec<ExpansionInput<'_>>,
        functions: &BTreeSet<&str>,
        source_functions: &BTreeSet<&str>,
    ) -> Result<Self, ProvenanceError> {
        let source_blake3 = hex(*blake3::hash(original.as_bytes()).as_bytes());
        let expanded_blake3 = hex(*blake3::hash(expanded.as_bytes()).as_bytes());
        let mut records = Vec::with_capacity(expansions.len());
        for (ordinal, e) in expansions.into_iter().enumerate() {
            let mut generated = e.generated;
            generated.sort_by_key(|r| (r.start, r.end));
            records.push(ExpansionRecord {
                ordinal: u32::try_from(ordinal)
                    .map_err(|_| ProvenanceError::Incomplete("expansion count".into()))?,
                r#macro: e.r#macro.to_owned(),
                invocation: e.invocation.into(),
                host_function: e.host_function.to_owned(),
                generated,
            });
        }
        let mut by_host: BTreeMap<&str, Vec<&ExpansionRecord>> = BTreeMap::new();
        for record in &records {
            by_host
                .entry(record.host_function.as_str())
                .or_default()
                .push(record);
        }
        let mut table_functions = Vec::with_capacity(functions.len());
        for &function in functions {
            if !source_functions.contains(function) {
                return Err(ProvenanceError::Incomplete(format!(
                    "IR function `{function}` has no source declaration"
                )));
            }
            let hosted = by_host.get(function).cloned().unwrap_or_default();
            let origin = if hosted.is_empty() {
                FunctionOrigin::Source
            } else {
                FunctionOrigin::Expanded
            };
            table_functions.push(FunctionProvenance {
                function: function.to_owned(),
                origin,
                expansions: hosted.iter().map(|r| r.ordinal).collect(),
                digest: function_digest(
                    &source_blake3,
                    &expanded_blake3,
                    function,
                    origin,
                    &hosted,
                ),
            });
        }
        let mut table = Self {
            schema: SCHEMA.to_owned(),
            package: package.to_owned(),
            source_blake3,
            expanded_blake3,
            expansions: records,
            functions: table_functions,
            digest: String::new(),
        };
        table.digest = table.compute_digest();
        table.verify(Some((original, expanded)))?;
        Ok(table)
    }

    fn compute_digest(&self) -> String {
        let mut unsigned = self.clone();
        unsigned.digest.clear();
        canonical_digest(&unsigned)
    }

    /// Check internal consistency and, when the sources are available, that
    /// the table is bound to exactly those bytes. Every expansion must name a
    /// function that is recorded as expanded, every expanded function must
    /// list exactly its expansions, and every digest must be recomputable.
    pub fn verify(&self, sources: Option<(&str, &str)>) -> Result<(), ProvenanceError> {
        if self.schema != SCHEMA {
            return Err(ProvenanceError::Schema);
        }
        if let Some((original, expanded)) = sources {
            if hex(*blake3::hash(original.as_bytes()).as_bytes()) != self.source_blake3 {
                return Err(ProvenanceError::Mismatch("original source hash".into()));
            }
            if hex(*blake3::hash(expanded.as_bytes()).as_bytes()) != self.expanded_blake3 {
                return Err(ProvenanceError::Mismatch("expanded source hash".into()));
            }
            for record in &self.expansions {
                if !within(&record.invocation, original)
                    || record.generated.iter().any(|r| !within(r, expanded))
                {
                    return Err(ProvenanceError::Mismatch(format!(
                        "expansion {} ranges",
                        record.ordinal
                    )));
                }
            }
        }
        let mut names = BTreeSet::new();
        for function in &self.functions {
            if function.function.is_empty() || !names.insert(function.function.as_str()) {
                return Err(ProvenanceError::Incomplete(
                    "duplicate or empty function entry".into(),
                ));
            }
        }
        for (i, record) in self.expansions.iter().enumerate() {
            if record.ordinal as usize != i || record.r#macro.is_empty() {
                return Err(ProvenanceError::Incomplete(format!("expansion {i} record")));
            }
            let host = self
                .functions
                .iter()
                .find(|f| f.function == record.host_function)
                .ok_or_else(|| {
                    ProvenanceError::Incomplete(format!(
                        "expansion {i} names unknown function `{}`",
                        record.host_function
                    ))
                })?;
            if host.origin != FunctionOrigin::Expanded || !host.expansions.contains(&record.ordinal)
            {
                return Err(ProvenanceError::Incomplete(format!(
                    "function `{}` omits expansion {i}",
                    host.function
                )));
            }
        }
        for function in &self.functions {
            let hosted = self
                .expansions
                .iter()
                .filter(|r| r.host_function == function.function)
                .collect::<Vec<_>>();
            let ordinals = hosted.iter().map(|r| r.ordinal).collect::<Vec<_>>();
            let expected_origin = if hosted.is_empty() {
                FunctionOrigin::Source
            } else {
                FunctionOrigin::Expanded
            };
            if ordinals != function.expansions || expected_origin != function.origin {
                return Err(ProvenanceError::Incomplete(format!(
                    "function `{}` expansion list",
                    function.function
                )));
            }
            if function.digest
                != function_digest(
                    &self.source_blake3,
                    &self.expanded_blake3,
                    &function.function,
                    function.origin,
                    &hosted,
                )
            {
                return Err(ProvenanceError::Mismatch(format!(
                    "function `{}` digest",
                    function.function
                )));
            }
        }
        if self.digest != self.compute_digest() {
            return Err(ProvenanceError::Mismatch("table digest".into()));
        }
        Ok(())
    }

    pub fn function(&self, name: &str) -> Option<&FunctionProvenance> {
        self.functions.iter().find(|f| f.function == name)
    }

    /// Functions that contain expanded code.
    pub fn expanded_functions(&self) -> impl Iterator<Item = &FunctionProvenance> {
        self.functions
            .iter()
            .filter(|f| f.origin == FunctionOrigin::Expanded)
    }
}

/// Map an expanded-source span to its original origin using the artifact's
/// source map. A span that overlaps a generated segment is attributed to that
/// macro invocation (the innermost, i.e. first overlapping, generated
/// segment); otherwise to the source segment that contains its start.
pub fn origin_of(map: &[SourceMapSegment], span: &Span) -> Option<DiagnosticOrigin> {
    let overlaps = |s: &SourceMapSegment| {
        let (a, b) = (s.expanded.start, s.expanded.end);
        if span.start == span.end {
            a <= span.start && span.start < b
        } else {
            a < span.end && span.start < b
        }
    };
    let generated = map
        .iter()
        .find(|s| matches!(s.kind, MapKind::Generated) && overlaps(s));
    // Segments are half-open and adjacent, so a span starting at a boundary
    // belongs to the following segment. Only a position at the very end of a
    // segment with no successor (end of file) falls back to the one before.
    let source = |s: &&SourceMapSegment| matches!(s.kind, MapKind::Source);
    let segment = generated
        .or_else(|| {
            map.iter()
                .filter(source)
                .find(|s| s.expanded.start <= span.start && span.start < s.expanded.end)
        })
        .or_else(|| {
            map.iter()
                .filter(source)
                .find(|s| s.expanded.start <= span.start && span.start == s.expanded.end)
        })?;
    let original = match segment.kind {
        MapKind::Generated => segment.original,
        MapKind::Source => {
            // Source segments are copied byte for byte, so offsets carry over.
            let start = segment.original.start + (span.start - segment.expanded.start);
            let len = span.end.saturating_sub(span.start);
            let end = (start + len).min(segment.original.end).max(start);
            ByteRange { start, end }
        }
    };
    Some(DiagnosticOrigin {
        expanded: span.into(),
        original,
        kind: segment.kind,
        r#macro: segment.r#macro.clone(),
    })
}

/// Attribute each diagnostic (and so each check/IR failure) to its origin.
/// The result is aligned with `diagnostics`.
pub fn diagnostic_origins(
    map: &[SourceMapSegment],
    diagnostics: &[Diagnostic],
) -> Vec<Option<DiagnosticOrigin>> {
    diagnostics
        .iter()
        .map(|d| origin_of(map, &d.span))
        .collect()
}

/// The source function that owns an extracted Lean declaration: the function
/// itself, its `f$suffix` companions (`$fuel`, `$contract`, ..) and its
/// `$block_f_N` body helpers.
pub fn lean_owner<'a>(declaration: &str, functions: &BTreeSet<&'a str>) -> Option<&'a str> {
    let candidate = if let Some(rest) = declaration.strip_prefix("$block_") {
        let (stem, index) = rest.rsplit_once('_')?;
        if index.is_empty() || !index.bytes().all(|b| b.is_ascii_digit()) {
            return None;
        }
        stem
    } else {
        declaration
            .split_once('$')
            .map_or(declaration, |(stem, _)| stem)
    };
    functions.get(candidate).copied()
}

fn declared_names(declaration: &Declaration, out: &mut Vec<String>) {
    let single = |name: &vesper_lean_syntax::Name| match name.components() {
        [only] => Some(only.as_str().to_owned()),
        _ => None,
    };
    match declaration {
        Declaration::Definition(d) => out.extend(single(&d.name)),
        Declaration::MutualDefinitions(ds) => out.extend(ds.iter().filter_map(|d| single(&d.name))),
        Declaration::Theorem { name, .. } => out.extend(single(name)),
        _ => {}
    }
}

/// A Lean extraction of an expanded artifact with provenance markers.
pub struct ProvenancedLean {
    pub text: String,
    /// `(Lean declaration, owning function)` for every marked declaration.
    pub marked: Vec<(String, String)>,
}

/// Extract the checked expanded program to Lean and append, inside the
/// `Vesper` namespace, a `$macro_provenance` string constant beside every
/// declaration owned by an expanded function (its value is that function's
/// provenance digest) and one module marker carrying the table digest. The
/// markers are ordinary kernel-checked definitions, so `vesper proof-audit`
/// reads them back from the replayed environment rather than from text.
pub fn extract_lean(artifact: &super::ExpandedChecked) -> Result<ProvenancedLean, String> {
    let table = artifact.provenance();
    table
        .verify(Some((
            artifact.original_source(),
            artifact.expanded_source(),
        )))
        .map_err(|e| e.to_string())?;
    let mut module = crate::lean::extract_report(artifact.checked().world())
        .map_err(|e| e.to_string())?
        .module;
    let functions = table
        .functions
        .iter()
        .map(|f| f.function.as_str())
        .collect::<BTreeSet<_>>();
    let namespace = module
        .declarations
        .iter_mut()
        .find_map(|d| match d {
            Declaration::Namespace { name, declarations }
                if matches!(name.components(), [only] if only.as_str() == "Vesper") =>
            {
                Some(declarations)
            }
            _ => None,
        })
        .ok_or("Lean extraction has no Vesper namespace")?;
    let mut names = Vec::new();
    for declaration in namespace.iter() {
        declared_names(declaration, &mut names);
    }
    let existing = names.iter().cloned().collect::<BTreeSet<_>>();
    let mut marked = Vec::new();
    let string = || {
        Term::Ref(
            vesper_lean_syntax::Name::qualified([Ident::new("String").expect("fixed name")])
                .expect("fixed name")
                .rooted(),
        )
    };
    let marker = |name: String, value: String| -> Result<Declaration, String> {
        if existing.contains(&name) {
            return Err(format!(
                "Lean declaration `{name}` collides with a provenance marker"
            ));
        }
        Ok(Declaration::Definition(Definition {
            name: crate::lean_nodes::source_name(&name)?,
            binders: vec![],
            result: string(),
            body: Term::String(value),
            kind: DefinitionKind::Def,
        }))
    };
    let mut markers = Vec::new();
    for name in &names {
        let Some(owner) = lean_owner(name, &functions) else {
            continue;
        };
        let record = table.function(owner).ok_or("function without provenance")?;
        if record.origin != FunctionOrigin::Expanded {
            continue;
        }
        markers.push(marker(
            format!("{name}{MARKER_SUFFIX}"),
            record.digest.clone(),
        )?);
        marked.push((name.clone(), owner.to_owned()));
    }
    for record in table.expanded_functions() {
        if !marked.iter().any(|(_, owner)| owner == &record.function) {
            return Err(format!(
                "macro provenance: expanded function `{}` has no Lean declaration",
                record.function
            ));
        }
    }
    markers.push(marker(MODULE_MARKER.to_owned(), table.digest.clone())?);
    namespace.extend(markers);
    Ok(ProvenancedLean {
        text: module.render().map_err(|e| e.to_string())?,
        marked,
    })
}
