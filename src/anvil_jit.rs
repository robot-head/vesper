//! Hot-swapped indirect-table JIT mutation engine and widened batch support
//! for Vesper Anvil (`docs/rfcs/vesper-anvil.md`, Phase 2–3).
//!
//! Compiles a module's reachable functions and a set of pre-checked mutant
//! variants `f$mut_k` into **one shared `JITModule`**, routing calls to
//! mutable functions through an `Arc<Vec<AtomicPtr<u8>>>` indirect dispatch
//! table (`call_indirect` loading the target pointer from the slot).
//!
//! Swapping a mutant is a single atomic pointer store (with an unwind-safe
//! RAII restore guard), avoiding per-mutant source re-parsing, re-checking,
//! and JIT recompilation.

use crate::{
    ast::{
        Arg, Expr, ExprKind, Function, Item, Literal, Module, Pass, Pattern, PatternKind, Span,
        Statement, Type,
    },
    check::World,
    ir::{FunctionIr, Op, Program, Terminator, ValueId},
    native::batch::BatchLimits,
    numeric::{IntegerKind, is_integer_name},
    runtime::{Value, integer_from_word},
};
use cranelift_codegen::{
    ir::{
        self, AbiParam, Block as ClifBlock, InstBuilder, MemFlags, Signature,
        condcodes::{FloatCC, IntCC},
        types,
    },
    settings::{self, Configurable},
};
use cranelift_frontend::{FunctionBuilder, FunctionBuilderContext, Variable};
use cranelift_jit::{JITBuilder, JITModule};
use cranelift_module::{FuncId, Linkage, Module as ClifModule};
use std::{
    collections::{BTreeMap, BTreeSet},
    marker::PhantomData,
    rc::Rc,
    sync::{
        Arc,
        atomic::{AtomicBool, AtomicPtr, AtomicU64, Ordering},
    },
};

/// The error a run reports when checked integer arithmetic fails.
const ARITH_FAILURE: &str = "anvil jit arithmetic failure: Fail[ArithOverflow]";

/// Default per-run fuel cap injected at loop headers and function entries so
/// mutants that introduce infinite loops or runaway recursion terminate
/// cleanly with an error instead of hanging the test runner.
pub const DEFAULT_JIT_FUEL: u64 = 100_000;

/// Classification of structured AST mutations generated by [`collect_ast_mutants`].
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum MutationKind {
    /// `<` <-> `<=`, `>` <-> `>=`.
    BoundaryFlip,
    /// `+` <-> `-`, `*` -> `+`, `/` -> `*`, `%` -> `/`.
    ArithmeticSwap,
    /// `true` <-> `false`, or removing unary `!`.
    BooleanFlip,
    /// `==` <-> `!=`.
    EqualityFlip,
    /// `&&` <-> `||`.
    LogicalFlip,
    /// Removing an assignment to a field of an `inout` place.
    DroppedInoutFieldAssign,
    /// Swapping two same-type `in` arguments in a call expression.
    SwappedInArgs,
}

/// A structured AST-level mutant generated directly on `vesper_core::ast::Function`.
#[derive(Clone, Debug)]
pub struct AstMutant {
    pub id: usize,
    pub fn_name: String,
    pub kind: MutationKind,
    pub description: String,
    pub span: Span,
    pub mutated_fn: Function,
}

impl AstMutant {
    /// Convert this AST mutant into a [`MutantVariant`] ready for
    /// [`HotSwapJitSession::compile`].
    pub fn to_variant(&self, mutant_idx: usize) -> MutantVariant {
        MutantVariant {
            target_fn: self.fn_name.clone(),
            mutant_id: mutant_idx,
            description: self.description.clone(),
            mutated_fn: self.mutated_fn.clone(),
        }
    }
}

/// A pre-checked mutant variant `f$mut_k` to be compiled into the shared
/// [`HotSwapJitSession`] alongside the baseline module.
#[derive(Clone, Debug)]
pub struct MutantVariant {
    /// Name of the baseline function in `World::functions`.
    pub target_fn: String,
    /// Per-function mutant index `k` (forming `f$mut_k`).
    pub mutant_id: usize,
    /// Human-readable description of the mutation.
    pub description: String,
    /// Mutated function AST with the same signature as `target_fn`.
    pub mutated_fn: Function,
}

/// Summary metrics for a compiled [`HotSwapJitSession`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct HotSwapStats {
    pub module_count: usize,
    pub baseline_functions: usize,
    pub mutant_functions: usize,
    pub dispatch_slots: usize,
    pub entry_count: usize,
    pub runs: u64,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum ScalarKind {
    Signed(u32),
    Unsigned(u32),
    Float64,
    Float32,
    Bool,
    Unit,
}

impl ScalarKind {
    fn of(ty: &Type) -> Result<Self, String> {
        if *ty == Type::unit() || ty.name() == "Unit" {
            return Ok(Self::Unit);
        }
        match ty {
            Type::IntLiteral(_) => Ok(Self::Signed(64)),
            Type::Named(name, args) if args.is_empty() => match name.as_str() {
                n if is_integer_name(n) => {
                    let k = IntegerKind::from_name(n).expect("verified integer name");
                    if k.wide() {
                        // The Anvil JIT lowers every integer to one word.
                        return Err(format!("anvil jit unsupported scalar type {ty}"));
                    }
                    if k.unsigned() {
                        Ok(Self::Unsigned(k.bits()))
                    } else {
                        Ok(Self::Signed(k.bits()))
                    }
                }
                "f64" => Ok(Self::Float64),
                "f32" => Ok(Self::Float32),
                "bool" => Ok(Self::Bool),
                _ => Err(format!("anvil jit unsupported scalar type {ty}")),
            },
            _ => Err(format!("anvil jit unsupported scalar type {ty}")),
        }
    }

    fn clif_type(self) -> ir::Type {
        match self {
            Self::Float64 => types::F64,
            Self::Float32 => types::F32,
            Self::Signed(_) | Self::Unsigned(_) | Self::Bool | Self::Unit => types::I64,
        }
    }

    fn is_unsigned(self) -> bool {
        matches!(self, Self::Unsigned(_))
    }

    fn is_float(self) -> bool {
        matches!(self, Self::Float64 | Self::Float32)
    }
}

struct CompiledEntry {
    code: *const u8,
    result: ScalarKind,
}

struct MutableSlot {
    slot_idx: usize,
    baseline_ptr: *mut u8,
    mutants: BTreeMap<usize, *mut u8>,
}

/// Runtime fuel state shared between Rust and the JIT-compiled functions.
/// Heap-pinned via `Box` so its address remains stable for the entire lifetime
/// of the `JITModule`.
struct FuelState {
    remaining: AtomicU64,
    exhausted: AtomicBool,
    /// Set when checked integer arithmetic fails (overflow, division by
    /// zero): the evaluator and native code raise `Fail[ArithOverflow]`
    /// there, so the run reports a failure instead of a wrapped value.
    arith_failed: AtomicBool,
}

/// One shared Cranelift `JITModule` holding all reachable baseline functions
/// and all pre-checked mutant variants `f$mut_k`, wired through an atomic
/// indirect dispatch table.
///
/// Field declaration order is significant: `module` is freed first in `Drop`
/// before `dispatch_table` and `fuel_state` are deallocated.
pub struct HotSwapJitSession {
    module: Option<JITModule>,
    dispatch_table: Arc<Vec<AtomicPtr<u8>>>,
    fuel_state: Box<FuelState>,
    entries: BTreeMap<String, CompiledEntry>,
    slots: BTreeMap<String, MutableSlot>,
    baseline_functions: usize,
    mutant_functions: usize,
    runs: AtomicU64,
    max_runs: u64,
    fuel_per_run: u64,
    _single_thread: PhantomData<Rc<()>>,
}

impl HotSwapJitSession {
    /// Compile all reachable functions from `entries` together with `mutants`
    /// into one shared `JITModule`.
    ///
    /// Calls to any function referenced by `mutants` are lowered through
    /// `call_indirect` reading its slot in `dispatch_table`.
    pub fn compile(
        world: &World,
        entries: &[String],
        mutants: &[MutantVariant],
        limits: BatchLimits,
    ) -> Result<Self, String> {
        if entries.is_empty() || entries.len() > limits.max_entries {
            return Err("anvil jit entry count out of limits".into());
        }
        let unique_entries: BTreeSet<&str> = entries.iter().map(String::as_str).collect();
        if unique_entries.len() != entries.len() {
            return Err("anvil jit duplicate entry".into());
        }

        // Lower baseline program.
        let program = crate::ir::lower_world(world);
        let reachable = collect_reachable(world, &program, entries, limits)?;

        // Group valid mutants for reachable target functions.
        let mut grouped_mutants: BTreeMap<String, Vec<&MutantVariant>> = BTreeMap::new();
        for variant in mutants {
            if !reachable.contains(&variant.target_fn) {
                continue;
            }
            grouped_mutants
                .entry(variant.target_fn.clone())
                .or_default()
                .push(variant);
        }

        // Lower each mutant variant's FunctionIr by substituting it into a
        // cloned World (preserving checked type maps at untouched spans).
        let mut mutant_irs: BTreeMap<(String, usize), FunctionIr> = BTreeMap::new();
        for (fn_name, variants) in &grouped_mutants {
            for variant in variants {
                let mut mut_world = world.clone();
                mut_world
                    .functions
                    .insert(fn_name.clone(), variant.mutated_fn.clone());
                let mut_program = crate::ir::lower_world(&mut_world);
                let ir = mut_program.functions.get(fn_name).cloned().ok_or_else(|| {
                    format!("failed to lower mutant {fn_name}$mut_{}", variant.mutant_id)
                })?;
                validate_function_ir(world, &ir)?;
                mutant_irs.insert((fn_name.clone(), variant.mutant_id), ir);
            }
        }

        // Allocate the pinned indirect dispatch table BEFORE codegen so each
        // mutable function's slot address can be embedded in `call_indirect`.
        let mutable_fn_names: Vec<String> = grouped_mutants.keys().cloned().collect();
        let slot_indices: BTreeMap<String, usize> = mutable_fn_names
            .iter()
            .enumerate()
            .map(|(idx, name)| (name.clone(), idx))
            .collect();
        let dispatch_table: Arc<Vec<AtomicPtr<u8>>> = Arc::new(
            (0..mutable_fn_names.len())
                .map(|_| AtomicPtr::new(std::ptr::null_mut()))
                .collect(),
        );
        let fuel_state = Box::new(FuelState {
            remaining: AtomicU64::new(DEFAULT_JIT_FUEL),
            exhausted: AtomicBool::new(false),
            arith_failed: AtomicBool::new(false),
        });

        // Create the single shared Cranelift JITModule.
        let mut flags = settings::builder();
        flags
            .set("use_colocated_libcalls", "false")
            .map_err(|e| e.to_string())?;
        flags.set("is_pic", "false").map_err(|e| e.to_string())?;
        if crate::native::needs_nan_canonicalization(world) {
            flags
                .set("enable_nan_canonicalization", "true")
                .map_err(|e| e.to_string())?;
        }
        let isa = cranelift_native::builder()
            .map_err(str::to_string)?
            .finish(settings::Flags::new(flags))
            .map_err(|e| e.to_string())?;
        let builder = JITBuilder::with_isa(isa, cranelift_module::default_libcall_names());
        let mut jit_module = JITModule::new(builder);

        // Compute Cranelift signatures for every reachable function.
        let mut sigs: BTreeMap<String, Signature> = BTreeMap::new();
        for name in &reachable {
            let f = &world.functions[name];
            sigs.insert(name.clone(), build_signature(&jit_module, f)?);
        }

        // Declare baseline functions once.
        let mut base_ids: BTreeMap<String, FuncId> = BTreeMap::new();
        for (i, name) in reachable.iter().enumerate() {
            let sym = format!("anvil_base_{i}_{name}");
            let id = jit_module
                .declare_function(&sym, Linkage::Local, &sigs[name])
                .map_err(|e| e.to_string())?;
            base_ids.insert(name.clone(), id);
        }

        // Declare mutant functions `f$mut_k` in the SAME JITModule.
        let mut mut_ids: BTreeMap<(String, usize), FuncId> = BTreeMap::new();
        for (fn_name, mutant_id) in mutant_irs.keys() {
            let sym = format!("anvil_mut_{fn_name}$mut_{mutant_id}");
            let id = jit_module
                .declare_function(&sym, Linkage::Local, &sigs[fn_name])
                .map_err(|e| e.to_string())?;
            mut_ids.insert((fn_name.clone(), *mutant_id), id);
        }

        let lower_env = LowerEnv {
            sigs: &sigs,
            base_ids: &base_ids,
            slot_indices: &slot_indices,
            table_base_addr: dispatch_table.as_ptr() as usize,
            fuel_remaining_addr: (&fuel_state.remaining as *const AtomicU64) as usize,
            fuel_exhausted_addr: (&fuel_state.exhausted as *const AtomicBool) as usize,
            arith_failed_addr: (&fuel_state.arith_failed as *const AtomicBool) as usize,
        };

        // Define all baseline functions.
        for name in &reachable {
            let ir = program
                .functions
                .get(name)
                .ok_or_else(|| format!("missing IR for baseline function {name}"))?;
            define_ir_function(&mut jit_module, base_ids[name], ir, &lower_env)?;
        }

        // Define all mutant functions `f$mut_k`.
        for ((fn_name, mutant_id), ir) in &mutant_irs {
            let id = mut_ids[&(fn_name.clone(), *mutant_id)];
            define_ir_function(&mut jit_module, id, ir, &lower_env)?;
        }

        // Finalize the single shared JITModule once.
        jit_module
            .finalize_definitions()
            .map_err(|e| e.to_string())?;

        // Populate the indirect dispatch table with baseline pointers and record
        // mutant code pointers.
        let mut slots = BTreeMap::new();
        for (fn_name, &slot_idx) in &slot_indices {
            let baseline_ptr = jit_module.get_finalized_function(base_ids[fn_name]) as *mut u8;
            dispatch_table[slot_idx].store(baseline_ptr, Ordering::Release);
            let mut mutants_map = BTreeMap::new();
            if let Some(variants) = grouped_mutants.get(fn_name) {
                for variant in variants {
                    let mid = variant.mutant_id;
                    let mptr = jit_module.get_finalized_function(mut_ids[&(fn_name.clone(), mid)])
                        as *mut u8;
                    mutants_map.insert(mid, mptr);
                }
            }
            slots.insert(
                fn_name.clone(),
                MutableSlot {
                    slot_idx,
                    baseline_ptr,
                    mutants: mutants_map,
                },
            );
        }

        // Collect entry points.
        let mut compiled_entries = BTreeMap::new();
        for name in entries {
            let f = &world.functions[name];
            if !f.params.is_empty() {
                return Err(format!("anvil jit entry '{name}' must take no parameters"));
            }
            let result = ScalarKind::of(&f.result)?;
            let code = jit_module.get_finalized_function(base_ids[name]);
            compiled_entries.insert(name.clone(), CompiledEntry { code, result });
        }

        Ok(Self {
            module: Some(jit_module),
            dispatch_table,
            fuel_state,
            entries: compiled_entries,
            slots,
            baseline_functions: reachable.len(),
            mutant_functions: mut_ids.len(),
            runs: AtomicU64::new(0),
            max_runs: limits.max_runs,
            fuel_per_run: DEFAULT_JIT_FUEL,
            _single_thread: PhantomData,
        })
    }

    /// Override the per-run fuel cap injected at loop headers and function entries.
    pub fn set_fuel(&mut self, fuel: u64) {
        self.fuel_per_run = fuel.max(1);
    }

    /// Inspect session compilation and execution statistics.
    pub fn stats(&self) -> HotSwapStats {
        HotSwapStats {
            module_count: 1,
            baseline_functions: self.baseline_functions,
            mutant_functions: self.mutant_functions,
            dispatch_slots: self.dispatch_table.len(),
            entry_count: self.entries.len(),
            runs: self.runs.load(Ordering::Relaxed),
        }
    }

    /// Clone the `Arc` handle to the indirect dispatch table (for diagnostics
    /// or testing).
    pub fn dispatch_table(&self) -> Arc<Vec<AtomicPtr<u8>>> {
        Arc::clone(&self.dispatch_table)
    }

    /// Execute a compiled zero-argument entry function in the shared `JITModule`.
    pub fn run_entry(&self, name: &str) -> Result<Value, String> {
        let entry = self
            .entries
            .get(name)
            .ok_or_else(|| format!("unknown anvil jit entry '{name}'"))?;
        let current = self.runs.fetch_add(1, Ordering::Relaxed);
        if current >= self.max_runs {
            return Err("anvil jit run limit exceeded".into());
        }

        self.fuel_state
            .remaining
            .store(self.fuel_per_run, Ordering::Release);
        self.fuel_state.exhausted.store(false, Ordering::Release);
        self.fuel_state.arith_failed.store(false, Ordering::Release);

        // SAFETY: `compile` verified that every entry takes 0 arguments, uses
        // the host C calling convention, and returns the exact scalar ABI type
        // matching `entry.result`. `self` owns the `JITModule`, dispatch table,
        // and `FuelState`, and is `!Send + !Sync`.
        let value = unsafe {
            match entry.result {
                ScalarKind::Float64 => {
                    let call: unsafe extern "C" fn() -> f64 = std::mem::transmute(entry.code);
                    Value::Float(call())
                }
                ScalarKind::Float32 => {
                    let call: unsafe extern "C" fn() -> f32 = std::mem::transmute(entry.code);
                    Value::Float32(call())
                }
                kind => {
                    let call: unsafe extern "C" fn() -> i64 = std::mem::transmute(entry.code);
                    let raw = call();
                    if self.fuel_state.arith_failed.load(Ordering::Acquire) {
                        return Err(ARITH_FAILURE.into());
                    }
                    if self.fuel_state.exhausted.load(Ordering::Acquire) {
                        return Err("anvil jit fuel exhausted".into());
                    }
                    decode_i64_result(kind, raw)?
                }
            }
        };

        if self.fuel_state.arith_failed.load(Ordering::Acquire) {
            return Err(ARITH_FAILURE.into());
        }
        if self.fuel_state.exhausted.load(Ordering::Acquire) {
            return Err("anvil jit fuel exhausted".into());
        }

        Ok(value)
    }

    /// Atomically swap the indirect dispatch slot for `fn_name` to mutant
    /// `f$mut_{mutant_idx}`, execute `f`, and unconditionally restore the
    /// baseline pointer (even if `f` returns an error or unwinds via panic).
    pub fn with_mutant<F, R>(&self, fn_name: &str, mutant_idx: usize, f: F) -> Result<R, String>
    where
        F: FnOnce() -> R,
    {
        let slot_info = self
            .slots
            .get(fn_name)
            .ok_or_else(|| format!("function '{fn_name}' has no hot-swap dispatch slot"))?;
        let &mutant_ptr = slot_info.mutants.get(&mutant_idx).ok_or_else(|| {
            format!("mutant {fn_name}$mut_{mutant_idx} not compiled in this session")
        })?;
        let slot = &self.dispatch_table[slot_info.slot_idx];

        struct RestoreGuard<'a> {
            slot: &'a AtomicPtr<u8>,
            baseline: *mut u8,
        }
        impl Drop for RestoreGuard<'_> {
            fn drop(&mut self) {
                self.slot.store(self.baseline, Ordering::Release);
            }
        }

        let _guard = RestoreGuard {
            slot,
            baseline: slot_info.baseline_ptr,
        };
        slot.store(mutant_ptr, Ordering::Release);
        Ok(f())
    }
}

impl Drop for HotSwapJitSession {
    fn drop(&mut self) {
        if let Some(module) = self.module.take() {
            // SAFETY: all compiled code pointers are private to `self`, no
            // calls can be in flight during `&mut self` drop, and `self` is
            // `!Send + !Sync`.
            unsafe {
                module.free_memory();
            }
        }
    }
}

fn decode_i64_result(kind: ScalarKind, raw: i64) -> Result<Value, String> {
    match kind {
        ScalarKind::Signed(bits) => Ok(integer_from_word(
            if bits == 64 {
                IntegerKind::I64
            } else {
                IntegerKind::from_name(&format!("i{bits}")).expect("signed width")
            },
            raw as u64,
        )),
        ScalarKind::Unsigned(bits) => {
            let mask = if bits == 64 {
                u64::MAX
            } else {
                (1u64 << bits) - 1
            };
            Ok(Value::UInt((raw as u64) & mask, bits))
        }
        ScalarKind::Bool => match raw {
            0 => Ok(Value::Bool(false)),
            1 => Ok(Value::Bool(true)),
            other => Err(format!("noncanonical anvil jit bool result {other}")),
        },
        ScalarKind::Unit => Ok(Value::Tuple(vec![])),
        ScalarKind::Float64 | ScalarKind::Float32 => unreachable!(),
    }
}

fn collect_reachable(
    world: &World,
    program: &Program,
    entries: &[String],
    limits: BatchLimits,
) -> Result<BTreeSet<String>, String> {
    let mut reachable = BTreeSet::new();
    let mut todo: Vec<String> = entries.to_vec();
    while let Some(name) = todo.pop() {
        if !reachable.insert(name.clone()) {
            continue;
        }
        if reachable.len() > limits.max_functions {
            return Err("anvil jit reachable function limit exceeded".into());
        }
        let f = world
            .functions
            .get(&name)
            .ok_or_else(|| format!("unknown function '{name}'"))?;
        if f.body.is_none() {
            return Err(format!(
                "anvil jit rejects extern/bodyless function '{name}'"
            ));
        }
        if !f.generics.is_empty() {
            return Err(format!("anvil jit requires monomorphic function '{name}'"));
        }
        ScalarKind::of(&f.result)?;
        for p in &f.params {
            if p.pass == Pass::Inout {
                return Err(format!(
                    "anvil jit does not yet lower inout parameter '{}' of '{name}'",
                    p.name
                ));
            }
            ScalarKind::of(&p.ty)?;
        }
        let ir = program
            .functions
            .get(&name)
            .ok_or_else(|| format!("missing IR for function '{name}'"))?;
        validate_function_ir(world, ir)?;
        for block in &ir.blocks {
            for inst in &block.instructions {
                if let Op::Call { callee, .. } = &inst.op {
                    if !world.functions.contains_key(callee) {
                        return Err(format!("anvil jit unresolved call '{callee}'"));
                    }
                    todo.push(callee.clone());
                }
            }
        }
    }
    Ok(reachable)
}

fn validate_function_ir(world: &World, ir: &FunctionIr) -> Result<(), String> {
    // Locals and values fall back to one word when their kind is unknown,
    // which would truncate an `i128`/`u128`, so refuse those outright.
    let wide = |t: &Type| IntegerKind::from_type(t).is_some_and(IntegerKind::wide);
    if ir.locals.values().any(wide) || ir.values.values().any(wide) {
        return Err(format!(
            "anvil jit unsupported 128-bit integer in '{}'",
            ir.name
        ));
    }
    for block in &ir.blocks {
        for inst in &block.instructions {
            match &inst.op {
                Op::Constant(Literal::String(_))
                | Op::Indirect { .. }
                | Op::Closure { .. }
                | Op::Handle { .. }
                | Op::Data(_, _)
                | Op::Project(_, _)
                | Op::Index(_, _)
                | Op::Try(_)
                | Op::Vector { .. }
                | Op::Tiled { .. }
                | Op::Seq { .. }
                | Op::Fip { .. } => {
                    return Err(format!(
                        "anvil jit unsupported IR operation in '{}'",
                        ir.name
                    ));
                }
                Op::Call {
                    callee,
                    args,
                    types,
                    capability,
                } => {
                    if capability.is_some()
                        || !types.is_empty()
                        || args.iter().any(|a| a.pass == Pass::Inout)
                    {
                        return Err(format!(
                            "anvil jit unsupported call form to '{callee}' in '{}'",
                            ir.name
                        ));
                    }
                    if !world.functions.contains_key(callee) {
                        return Err(format!("anvil jit unknown callee '{callee}'"));
                    }
                }
                Op::Tuple(es) if !es.is_empty() => {
                    return Err(format!("anvil jit non-unit tuple in '{}'", ir.name));
                }
                _ => {}
            }
        }
    }
    Ok(())
}

fn build_signature(module: &JITModule, f: &Function) -> Result<Signature, String> {
    let mut sig = module.make_signature();
    for p in &f.params {
        let kind = ScalarKind::of(&p.ty)?;
        sig.params.push(AbiParam::new(kind.clif_type()));
    }
    let ret = ScalarKind::of(&f.result)?;
    sig.returns.push(AbiParam::new(ret.clif_type()));
    Ok(sig)
}

struct LowerEnv<'a> {
    sigs: &'a BTreeMap<String, Signature>,
    base_ids: &'a BTreeMap<String, FuncId>,
    slot_indices: &'a BTreeMap<String, usize>,
    table_base_addr: usize,
    fuel_remaining_addr: usize,
    fuel_exhausted_addr: usize,
    arith_failed_addr: usize,
}

fn define_ir_function(
    module: &mut JITModule,
    func_id: FuncId,
    ir_fn: &FunctionIr,
    env: &LowerEnv<'_>,
) -> Result<(), String> {
    let mut ctx = module.make_context();
    ctx.func.signature = env.sigs[&ir_fn.name].clone();

    let ptr_ty = module.target_config().pointer_type();
    let ret_kind = ScalarKind::of(&ir_fn.result)?;

    let mut fb_ctx = FunctionBuilderContext::new();
    let mut b = FunctionBuilder::new(&mut ctx.func, &mut fb_ctx);

    let clif_blocks: Vec<ClifBlock> = (0..ir_fn.blocks.len()).map(|_| b.create_block()).collect();
    if clif_blocks.is_empty() {
        return Err(format!("function '{}' has no IR blocks", ir_fn.name));
    }

    // Attach entry block parameters matching function signature.
    b.append_block_params_for_function_params(clif_blocks[0]);

    // Attach block parameters for non-entry blocks that have phi params.
    for (idx, block) in ir_fn.blocks.iter().enumerate().skip(1) {
        for &vid in &block.params {
            let ty = ir_fn
                .values
                .get(&vid)
                .and_then(|t| ScalarKind::of(t).ok())
                .unwrap_or(ScalarKind::Signed(64))
                .clif_type();
            b.append_block_param(clif_blocks[idx], ty);
        }
    }

    // Declare Cranelift SSA variables for every IR local and every IR ValueId.
    let mut local_vars: BTreeMap<String, (Variable, ScalarKind)> = BTreeMap::new();
    for p in &ir_fn.params {
        let kind = ScalarKind::of(&p.ty)?;
        let var = b.declare_var(kind.clif_type());
        local_vars.insert(p.name.clone(), (var, kind));
    }
    for (local_name, ty) in &ir_fn.locals {
        if !local_vars.contains_key(local_name) {
            let kind = ScalarKind::of(ty).unwrap_or(ScalarKind::Signed(64));
            let var = b.declare_var(kind.clif_type());
            local_vars.insert(local_name.clone(), (var, kind));
        }
    }

    let mut value_vars: BTreeMap<ValueId, (Variable, ScalarKind)> = BTreeMap::new();
    for (&vid, ty) in &ir_fn.values {
        let kind = ScalarKind::of(ty).unwrap_or(ScalarKind::Signed(64));
        let var = b.declare_var(kind.clif_type());
        value_vars.insert(vid, (var, kind));
    }

    // Emit a shared early-exit block for fuel exhaustion.
    let exhausted_block = b.create_block();
    // And one for checked integer arithmetic that fails.
    let arith_block = b.create_block();

    for (block_idx, block) in ir_fn.blocks.iter().enumerate() {
        b.switch_to_block(clif_blocks[block_idx]);

        if block_idx == 0 {
            let entry_params: Vec<ir::Value> = b.block_params(clif_blocks[0]).to_vec();
            for (p, &val) in ir_fn.params.iter().zip(&entry_params) {
                let (var, _) = local_vars[&p.name];
                b.def_var(var, val);
            }
            // Fuel check on function entry (bounds runaway recursion).
            let cont_block = b.create_block();
            emit_fuel_check(&mut b, ptr_ty, env, exhausted_block, cont_block);
            b.switch_to_block(cont_block);
        } else if !block.params.is_empty() {
            let params: Vec<ir::Value> = b.block_params(clif_blocks[block_idx]).to_vec();
            for (&vid, &val) in block.params.iter().zip(&params) {
                if let Some(&(var, _)) = value_vars.get(&vid) {
                    b.def_var(var, val);
                }
            }
        }

        let mut terminated = false;
        for inst in &block.instructions {
            if terminated {
                break;
            }
            let dest_kind = ScalarKind::of(&inst.ty).unwrap_or(ScalarKind::Signed(64));
            let result_val = match &inst.op {
                Op::Constant(lit) => emit_literal(&mut b, lit, dest_kind)?,
                Op::Unit | Op::Tuple(_) => b.ins().iconst(types::I64, 0),
                Op::Loop => {
                    // Inject fuel check at every loop header so infinite-loop
                    // mutants terminate cleanly.
                    let cont_block = b.create_block();
                    emit_fuel_check(&mut b, ptr_ty, env, exhausted_block, cont_block);
                    b.switch_to_block(cont_block);
                    b.ins().iconst(types::I64, 0)
                }
                Op::Read { root, .. } => {
                    if let Some(&(var, _)) = local_vars.get(root) {
                        b.use_var(var)
                    } else {
                        return Err(format!(
                            "anvil jit unknown local '{root}' in '{}'",
                            ir_fn.name
                        ));
                    }
                }
                Op::Bind { pattern, value } => {
                    let val = load_val(&mut b, &value_vars, *value)?;
                    match &pattern.kind {
                        PatternKind::Bind(name) => {
                            if let Some(&(var, _)) = local_vars.get(name) {
                                b.def_var(var, val);
                            } else {
                                let var = b.declare_var(b.func.dfg.value_type(val));
                                b.def_var(var, val);
                                local_vars.insert(name.clone(), (var, dest_kind));
                            }
                        }
                        PatternKind::Wild => {}
                        _ => {
                            return Err(format!(
                                "anvil jit unsupported bind pattern in '{}'",
                                ir_fn.name
                            ));
                        }
                    }
                    b.ins().iconst(types::I64, 0)
                }
                Op::Write { place, op, value } => {
                    let rhs = load_val(&mut b, &value_vars, *value)?;
                    let (var, kind) = *local_vars.get(place).ok_or_else(|| {
                        format!(
                            "anvil jit unknown write place '{place}' in '{}'",
                            ir_fn.name
                        )
                    })?;
                    let new_val = match op.as_str() {
                        "=" => rhs,
                        "+=" | "-=" | "*=" | "/=" | "%=" => {
                            let cur = b.use_var(var);
                            let bin_op = &op[..1];
                            emit_arith_guard(&mut b, bin_op, cur, rhs, kind, arith_block);
                            emit_binary(&mut b, bin_op, cur, rhs, kind)?
                        }
                        other => return Err(format!("anvil jit unsupported assign op '{other}'")),
                    };
                    b.def_var(var, new_val);
                    b.ins().iconst(types::I64, 0)
                }
                Op::Unary(op, operand) => {
                    let v = load_val(&mut b, &value_vars, *operand)?;
                    let op_kind = value_vars
                        .get(operand)
                        .map(|(_, k)| *k)
                        .unwrap_or(dest_kind);
                    match op.as_str() {
                        "-" => {
                            if op_kind.is_float() {
                                b.ins().fneg(v)
                            } else {
                                let zero = b.ins().iconst(types::I64, 0);
                                emit_arith_guard(&mut b, "-", zero, v, op_kind, arith_block);
                                b.ins().ineg(v)
                            }
                        }
                        "!" => {
                            let zero = b.ins().iconst(types::I64, 0);
                            let cmp = b.ins().icmp(IntCC::Equal, v, zero);
                            b.ins().uextend(types::I64, cmp)
                        }
                        other => return Err(format!("anvil jit unsupported unary op '{other}'")),
                    }
                }
                Op::Binary(op, lhs_id, rhs_id) => {
                    let lhs = load_val(&mut b, &value_vars, *lhs_id)?;
                    let rhs = load_val(&mut b, &value_vars, *rhs_id)?;
                    let op_kind = value_vars.get(lhs_id).map(|(_, k)| *k).unwrap_or(dest_kind);
                    emit_arith_guard(&mut b, op, lhs, rhs, op_kind, arith_block);
                    emit_binary(&mut b, op, lhs, rhs, op_kind)?
                }
                Op::Call { callee, args, .. } => {
                    let mut arg_vals = Vec::with_capacity(args.len());
                    for arg in args {
                        arg_vals.push(load_val(&mut b, &value_vars, arg.value)?);
                    }
                    let call_inst = if let Some(&slot_idx) = env.slot_indices.get(callee) {
                        // Indirect call through the module's atomic dispatch table!
                        let slot_addr =
                            env.table_base_addr + slot_idx * std::mem::size_of::<AtomicPtr<u8>>();
                        let addr_val = b.ins().iconst(ptr_ty, slot_addr as i64);
                        let fn_ptr = b.ins().load(ptr_ty, MemFlags::trusted(), addr_val, 0);
                        let sig_ref = b.import_signature(env.sigs[callee].clone());
                        b.ins().call_indirect(sig_ref, fn_ptr, &arg_vals)
                    } else {
                        let callee_id = env.base_ids[callee];
                        let func_ref = module.declare_func_in_func(callee_id, b.func);
                        b.ins().call(func_ref, &arg_vals)
                    };
                    let results = b.inst_results(call_inst);
                    if let Some(&first) = results.first() {
                        first
                    } else {
                        b.ins().iconst(types::I64, 0)
                    }
                }
                Op::Exit { value, .. } => {
                    let ret_val = load_val(&mut b, &value_vars, *value)?;
                    b.ins().return_(&[ret_val]);
                    terminated = true;
                    continue;
                }
                _ => {
                    return Err(format!("anvil jit unsupported IR op in '{}'", ir_fn.name));
                }
            };

            if let Some(&(var, _)) = value_vars.get(&inst.dest) {
                b.def_var(var, result_val);
            } else {
                let var = b.declare_var(b.func.dfg.value_type(result_val));
                b.def_var(var, result_val);
                value_vars.insert(inst.dest, (var, dest_kind));
            }
        }

        if !terminated {
            match &block.terminator {
                Terminator::Return(vid) => {
                    let val = load_val(&mut b, &value_vars, *vid)?;
                    b.ins().return_(&[val]);
                }
                Terminator::Jump {
                    block: target,
                    args,
                } => {
                    let mut jump_args = Vec::with_capacity(args.len());
                    for &arg in args {
                        jump_args.push(ir::BlockArg::Value(load_val(&mut b, &value_vars, arg)?));
                    }
                    b.ins().jump(clif_blocks[*target], &jump_args);
                }
                Terminator::Branch { condition, yes, no } => {
                    let cond = load_val(&mut b, &value_vars, *condition)?;
                    b.ins()
                        .brif(cond, clif_blocks[*yes], &[], clif_blocks[*no], &[]);
                }
                Terminator::Match { value, arms } => {
                    let scrutinee = load_val(&mut b, &value_vars, *value)?;
                    emit_match_terminator(&mut b, scrutinee, arms, &clif_blocks)?;
                }
                Terminator::Unreachable => {
                    let zero = default_zero(&mut b, ret_kind);
                    b.ins().return_(&[zero]);
                }
            }
        }
    }

    // Define the shared fuel-exhausted exit block.
    b.switch_to_block(exhausted_block);
    let flag_addr = b.ins().iconst(ptr_ty, env.fuel_exhausted_addr as i64);
    let one_byte = b.ins().iconst(types::I8, 1);
    b.ins().store(MemFlags::trusted(), one_byte, flag_addr, 0);
    let zero = default_zero(&mut b, ret_kind);
    b.ins().return_(&[zero]);

    // Define the shared checked-arithmetic failure exit block.
    b.switch_to_block(arith_block);
    let flag_addr = b.ins().iconst(ptr_ty, env.arith_failed_addr as i64);
    let one_byte = b.ins().iconst(types::I8, 1);
    b.ins().store(MemFlags::trusted(), one_byte, flag_addr, 0);
    let zero = default_zero(&mut b, ret_kind);
    b.ins().return_(&[zero]);

    b.seal_all_blocks();
    b.finalize();

    module
        .define_function(func_id, &mut ctx)
        .map_err(|e| format!("cranelift define_function '{}' failed: {e}", ir_fn.name))?;
    Ok(())
}

fn emit_fuel_check(
    b: &mut FunctionBuilder<'_>,
    ptr_ty: ir::Type,
    env: &LowerEnv<'_>,
    exhausted_block: ClifBlock,
    cont_block: ClifBlock,
) {
    let fuel_addr = b.ins().iconst(ptr_ty, env.fuel_remaining_addr as i64);
    let cur = b.ins().load(types::I64, MemFlags::trusted(), fuel_addr, 0);
    let zero = b.ins().iconst(types::I64, 0);
    let is_zero = b.ins().icmp(IntCC::Equal, cur, zero);
    let dec_block = b.create_block();
    b.ins().brif(is_zero, exhausted_block, &[], dec_block, &[]);

    b.switch_to_block(dec_block);
    let next = b.ins().iadd_imm(cur, -1);
    b.ins().store(MemFlags::trusted(), next, fuel_addr, 0);
    b.ins().jump(cont_block, &[]);
}

fn default_zero(b: &mut FunctionBuilder<'_>, kind: ScalarKind) -> ir::Value {
    match kind {
        ScalarKind::Float64 => b.ins().f64const(0.0),
        ScalarKind::Float32 => b.ins().f32const(0.0),
        _ => b.ins().iconst(types::I64, 0),
    }
}

fn load_val(
    b: &mut FunctionBuilder<'_>,
    value_vars: &BTreeMap<ValueId, (Variable, ScalarKind)>,
    vid: ValueId,
) -> Result<ir::Value, String> {
    let &(var, _) = value_vars
        .get(&vid)
        .ok_or_else(|| format!("anvil jit missing IR value v{vid}"))?;
    Ok(b.use_var(var))
}

fn emit_literal(
    b: &mut FunctionBuilder<'_>,
    lit: &Literal,
    kind: ScalarKind,
) -> Result<ir::Value, String> {
    match lit {
        Literal::Int(n) => Ok(b.ins().iconst(types::I64, *n as i64)),
        Literal::Bool(v) => Ok(b.ins().iconst(types::I64, i64::from(*v))),
        Literal::Float(f) => match kind {
            ScalarKind::Float32 => Ok(b.ins().f32const(*f as f32)),
            _ => Ok(b.ins().f64const(*f)),
        },
        Literal::String(_) => Err("anvil jit string literal unsupported".into()),
    }
}

/// Branches to `fail_block` when the checked integer operation `lhs op rhs`
/// fails under Vesper's semantics (the checks of
/// `native::checked_arithmetic`, plus a zero divisor), so the hot-swap JIT
/// reports a failure where the evaluator and native code raise
/// `Fail[ArithOverflow]`, instead of returning a wrapped value. Integers
/// live sign- or zero-extended in 64 bits, so a narrow result is in range
/// iff re-extending it from the kind's width leaves it unchanged.
fn emit_arith_guard(
    b: &mut FunctionBuilder<'_>,
    op: &str,
    lhs: ir::Value,
    rhs: ir::Value,
    kind: ScalarKind,
    fail_block: ClifBlock,
) {
    let (signed, bits) = match kind {
        ScalarKind::Signed(bits) => (true, bits),
        ScalarKind::Unsigned(bits) => (false, bits),
        _ => return,
    };
    let failed = match op {
        "+" | "-" | "*" if bits < 64 => {
            let r = match op {
                "+" => b.ins().iadd(lhs, rhs),
                "-" => b.ins().isub(lhs, rhs),
                _ => b.ins().imul(lhs, rhs),
            };
            if signed {
                let up = i64::from(64 - bits);
                let high = b.ins().ishl_imm(r, up);
                let canonical = b.ins().sshr_imm(high, up);
                b.ins().icmp(IntCC::NotEqual, canonical, r)
            } else {
                let mask = (1u64 << bits) - 1;
                b.ins().icmp_imm(IntCC::UnsignedGreaterThan, r, mask as i64)
            }
        }
        "+" if !signed => {
            let r = b.ins().iadd(lhs, rhs);
            b.ins().icmp(IntCC::UnsignedLessThan, r, lhs)
        }
        "-" if !signed => b.ins().icmp(IntCC::UnsignedLessThan, lhs, rhs),
        "*" if !signed => {
            let high = b.ins().umulhi(lhs, rhs);
            b.ins().icmp_imm(IntCC::NotEqual, high, 0)
        }
        "+" | "-" => {
            let r = if op == "+" {
                b.ins().iadd(lhs, rhs)
            } else {
                b.ins().isub(lhs, rhs)
            };
            let x = b.ins().bxor(lhs, r);
            let y = if op == "+" {
                b.ins().bxor(rhs, r)
            } else {
                b.ins().bxor(lhs, rhs)
            };
            let both = b.ins().band(x, y);
            b.ins().icmp_imm(IntCC::SignedLessThan, both, 0)
        }
        "*" => {
            let r = b.ins().imul(lhs, rhs);
            let high = b.ins().smulhi(lhs, rhs);
            let sign = b.ins().sshr_imm(r, 63);
            b.ins().icmp(IntCC::NotEqual, high, sign)
        }
        "/" | "%" => {
            let zero = b.ins().icmp_imm(IntCC::Equal, rhs, 0);
            if signed && op == "/" {
                // `MIN / -1` overflows (Cranelift's `srem` defines
                // `MIN % -1` as 0, as native code does).
                let min = if bits < 64 {
                    -(1i64 << (bits - 1))
                } else {
                    i64::MIN
                };
                let is_min = b.ins().icmp_imm(IntCC::Equal, lhs, min);
                let minus_one = b.ins().icmp_imm(IntCC::Equal, rhs, -1);
                let both = b.ins().band(is_min, minus_one);
                b.ins().bor(zero, both)
            } else {
                zero
            }
        }
        _ => return,
    };
    let cont = b.create_block();
    b.ins().brif(failed, fail_block, &[], cont, &[]);
    b.switch_to_block(cont);
}

fn emit_binary(
    b: &mut FunctionBuilder<'_>,
    op: &str,
    lhs: ir::Value,
    rhs: ir::Value,
    kind: ScalarKind,
) -> Result<ir::Value, String> {
    if kind.is_float() {
        return Ok(match op {
            "+" => b.ins().fadd(lhs, rhs),
            "-" => b.ins().fsub(lhs, rhs),
            "*" => b.ins().fmul(lhs, rhs),
            "/" => b.ins().fdiv(lhs, rhs),
            "==" => {
                let c = b.ins().fcmp(FloatCC::Equal, lhs, rhs);
                b.ins().uextend(types::I64, c)
            }
            "!=" => {
                let c = b.ins().fcmp(FloatCC::NotEqual, lhs, rhs);
                b.ins().uextend(types::I64, c)
            }
            "<" => {
                let c = b.ins().fcmp(FloatCC::LessThan, lhs, rhs);
                b.ins().uextend(types::I64, c)
            }
            "<=" => {
                let c = b.ins().fcmp(FloatCC::LessThanOrEqual, lhs, rhs);
                b.ins().uextend(types::I64, c)
            }
            ">" => {
                let c = b.ins().fcmp(FloatCC::GreaterThan, lhs, rhs);
                b.ins().uextend(types::I64, c)
            }
            ">=" => {
                let c = b.ins().fcmp(FloatCC::GreaterThanOrEqual, lhs, rhs);
                b.ins().uextend(types::I64, c)
            }
            other => return Err(format!("anvil jit unsupported float op '{other}'")),
        });
    }

    let unsigned = kind.is_unsigned();
    Ok(match op {
        "+" => b.ins().iadd(lhs, rhs),
        "-" => b.ins().isub(lhs, rhs),
        "*" => b.ins().imul(lhs, rhs),
        "/" => {
            if unsigned {
                b.ins().udiv(lhs, rhs)
            } else {
                b.ins().sdiv(lhs, rhs)
            }
        }
        "%" => {
            if unsigned {
                b.ins().urem(lhs, rhs)
            } else {
                b.ins().srem(lhs, rhs)
            }
        }
        "&" | "&&" => b.ins().band(lhs, rhs),
        "|" | "||" => b.ins().bor(lhs, rhs),
        "^" => b.ins().bxor(lhs, rhs),
        "<<" => b.ins().ishl(lhs, rhs),
        ">>" => {
            if unsigned {
                b.ins().ushr(lhs, rhs)
            } else {
                b.ins().sshr(lhs, rhs)
            }
        }
        "==" => {
            let c = b.ins().icmp(IntCC::Equal, lhs, rhs);
            b.ins().uextend(types::I64, c)
        }
        "!=" => {
            let c = b.ins().icmp(IntCC::NotEqual, lhs, rhs);
            b.ins().uextend(types::I64, c)
        }
        "<" => {
            let cc = if unsigned {
                IntCC::UnsignedLessThan
            } else {
                IntCC::SignedLessThan
            };
            let c = b.ins().icmp(cc, lhs, rhs);
            b.ins().uextend(types::I64, c)
        }
        "<=" => {
            let cc = if unsigned {
                IntCC::UnsignedLessThanOrEqual
            } else {
                IntCC::SignedLessThanOrEqual
            };
            let c = b.ins().icmp(cc, lhs, rhs);
            b.ins().uextend(types::I64, c)
        }
        ">" => {
            let cc = if unsigned {
                IntCC::UnsignedGreaterThan
            } else {
                IntCC::SignedGreaterThan
            };
            let c = b.ins().icmp(cc, lhs, rhs);
            b.ins().uextend(types::I64, c)
        }
        ">=" => {
            let cc = if unsigned {
                IntCC::UnsignedGreaterThanOrEqual
            } else {
                IntCC::SignedGreaterThanOrEqual
            };
            let c = b.ins().icmp(cc, lhs, rhs);
            b.ins().uextend(types::I64, c)
        }
        other => return Err(format!("anvil jit unsupported integer op '{other}'")),
    })
}

fn emit_match_terminator(
    b: &mut FunctionBuilder<'_>,
    scrutinee: ir::Value,
    arms: &[(Pattern, usize)],
    clif_blocks: &[ClifBlock],
) -> Result<(), String> {
    if arms.is_empty() {
        let zero = b.ins().iconst(types::I64, 0);
        b.ins().return_(&[zero]);
        return Ok(());
    }
    for (idx, (pat, target)) in arms.iter().enumerate() {
        let is_last = idx + 1 == arms.len();
        match &pat.kind {
            PatternKind::Wild | PatternKind::Bind(_) => {
                b.ins().jump(clif_blocks[*target], &[]);
                return Ok(());
            }
            PatternKind::Literal(Literal::Int(n)) => {
                let lit = b.ins().iconst(types::I64, *n as i64);
                let cmp = b.ins().icmp(IntCC::Equal, scrutinee, lit);
                if is_last {
                    b.ins().jump(clif_blocks[*target], &[]);
                } else {
                    let next = b.create_block();
                    b.ins().brif(cmp, clif_blocks[*target], &[], next, &[]);
                    b.switch_to_block(next);
                }
            }
            PatternKind::Literal(Literal::Bool(v)) => {
                let lit = b.ins().iconst(types::I64, i64::from(*v));
                let cmp = b.ins().icmp(IntCC::Equal, scrutinee, lit);
                if is_last {
                    b.ins().jump(clif_blocks[*target], &[]);
                } else {
                    let next = b.create_block();
                    b.ins().brif(cmp, clif_blocks[*target], &[], next, &[]);
                    b.switch_to_block(next);
                }
            }
            _ => {
                return Err("anvil jit unsupported match pattern".into());
            }
        }
    }
    Ok(())
}

// ---------------------------------------------------------------------------
// Structured AST Mutant Generator
// ---------------------------------------------------------------------------

/// Generate structured AST mutants directly on `module`'s non-test functions,
/// avoiding brittle raw source-string splicing.
///
/// Mutates:
/// - Boundary comparisons: `<` <-> `<=`, `>` <-> `>=`
/// - Arithmetic operators: `+` <-> `-`, `*` -> `+`, `/` -> `*`, `%` -> `/`
/// - Boolean literals (`true` <-> `false`) and unary `!`
/// - Equality operators: `==` <-> `!=`
/// - Logical operators: `&&` <-> `||`
/// - Dropped `inout` field assignments (e.g. `s.field = ...;` removed)
/// - Swapped same-type `in` arguments in calls to module functions
pub fn collect_ast_mutants(
    module: &Module,
    test_names: &BTreeSet<String>,
    max_mutants: usize,
) -> Vec<AstMutant> {
    if max_mutants == 0 {
        return Vec::new();
    }

    // Index known function signatures in the module so we can detect same-type
    // `in` arguments when mutating call expressions.
    let mut fn_param_sigs: BTreeMap<String, Vec<(Pass, Type)>> = BTreeMap::new();
    for item in &module.items {
        if let Item::Function(f) = item {
            fn_param_sigs.insert(
                f.name.clone(),
                f.params.iter().map(|p| (p.pass, p.ty.clone())).collect(),
            );
        }
    }

    let mut out = Vec::new();
    for item in &module.items {
        if out.len() >= max_mutants {
            break;
        }
        let Item::Function(func) = item else {
            continue;
        };
        if test_names.contains(&func.name) || func.body.is_none() {
            continue;
        }
        let inout_params: BTreeSet<String> = func
            .params
            .iter()
            .filter(|p| p.pass == Pass::Inout)
            .map(|p| p.name.clone())
            .collect();

        let body = func.body.as_ref().expect("checked body");
        let sites = collect_mutation_sites(body, &inout_params, &fn_param_sigs);
        for site in sites {
            if out.len() >= max_mutants {
                break;
            }
            let mut mutated_fn = (**func).clone();
            if let Some(mutated_body) = mutated_fn.body.as_mut()
                && apply_site(mutated_body, &site.path, &site.patch)
            {
                let id = out.len();
                out.push(AstMutant {
                    id,
                    fn_name: func.name.clone(),
                    kind: site.kind,
                    description: site.description,
                    span: site.span,
                    mutated_fn,
                });
            }
        }
    }
    out
}

#[derive(Clone, Debug)]
enum PathStep {
    BlockStmt(usize),
    BlockTail,
    IfCond,
    IfThen,
    IfElse,
    BinaryLhs,
    BinaryRhs,
    UnaryInner,
    CallCallee,
    CallArg(usize),
    AssignRhs,
    TupleElem(usize),
    StructField(usize),
    FieldBase,
    IndexBase,
    IndexIdx,
    TryInner,
    MatchVal,
    MatchArm(usize),
    LoopBody,
    ForIter,
    ForBody,
    BreakVal,
    ReturnVal,
    ClosureBody,
}

#[derive(Clone, Debug)]
enum Patch {
    BinaryOp(&'static str),
    FlipBool(bool),
    RemoveUnaryNot,
    DropBlockStmt(usize),
    SwapCallArgs(usize, usize),
}

struct MutationSite {
    path: Vec<PathStep>,
    patch: Patch,
    kind: MutationKind,
    description: String,
    span: Span,
}

fn collect_mutation_sites(
    root: &Expr,
    inout_params: &BTreeSet<String>,
    fn_param_sigs: &BTreeMap<String, Vec<(Pass, Type)>>,
) -> Vec<MutationSite> {
    let mut sites = Vec::new();
    let mut path = Vec::new();
    visit_expr(root, inout_params, fn_param_sigs, &mut path, &mut sites);
    sites
}

fn root_ident(expr: &Expr) -> Option<&str> {
    match &expr.kind {
        ExprKind::Name(n) => Some(n.as_str()),
        ExprKind::Field(base, _) | ExprKind::Index(base, _) => root_ident(base),
        _ => None,
    }
}

fn is_field_projection(expr: &Expr) -> bool {
    matches!(&expr.kind, ExprKind::Field(_, _))
}

fn visit_expr(
    expr: &Expr,
    inout_params: &BTreeSet<String>,
    fn_param_sigs: &BTreeMap<String, Vec<(Pass, Type)>>,
    path: &mut Vec<PathStep>,
    sites: &mut Vec<MutationSite>,
) {
    match &expr.kind {
        ExprKind::Literal(Literal::Bool(b)) => {
            sites.push(MutationSite {
                path: path.clone(),
                patch: Patch::FlipBool(!b),
                kind: MutationKind::BooleanFlip,
                description: format!("{b} -> {}", !b),
                span: expr.span.clone(),
            });
        }
        ExprKind::Unary(op, inner) => {
            if op == "!" {
                sites.push(MutationSite {
                    path: path.clone(),
                    patch: Patch::RemoveUnaryNot,
                    kind: MutationKind::BooleanFlip,
                    description: "remove unary '!'".into(),
                    span: expr.span.clone(),
                });
            }
            path.push(PathStep::UnaryInner);
            visit_expr(inner, inout_params, fn_param_sigs, path, sites);
            path.pop();
        }
        ExprKind::Binary(op, lhs, rhs) => {
            if let Some((replacement, kind)) = mutate_binary_op(op) {
                sites.push(MutationSite {
                    path: path.clone(),
                    patch: Patch::BinaryOp(replacement),
                    kind,
                    description: format!("{op} -> {replacement}"),
                    span: expr.span.clone(),
                });
            }
            path.push(PathStep::BinaryLhs);
            visit_expr(lhs, inout_params, fn_param_sigs, path, sites);
            path.pop();
            path.push(PathStep::BinaryRhs);
            visit_expr(rhs, inout_params, fn_param_sigs, path, sites);
            path.pop();
        }
        ExprKind::Block { statements, tail } => {
            for (idx, stmt) in statements.iter().enumerate() {
                if let Statement::Expr(e) = stmt
                    && let ExprKind::Assign(assign_op, lhs, _) = &e.kind
                    && is_field_projection(lhs)
                    && root_ident(lhs).is_some_and(|r| inout_params.contains(r))
                {
                    sites.push(MutationSite {
                        path: path.clone(),
                        patch: Patch::DropBlockStmt(idx),
                        kind: MutationKind::DroppedInoutFieldAssign,
                        description: format!("drop inout field assignment ({assign_op})"),
                        span: e.span.clone(),
                    });
                }
                path.push(PathStep::BlockStmt(idx));
                match stmt {
                    Statement::Let { value, .. } => {
                        visit_expr(value, inout_params, fn_param_sigs, path, sites);
                    }
                    Statement::Expr(e) => {
                        visit_expr(e, inout_params, fn_param_sigs, path, sites);
                    }
                }
                path.pop();
            }
            if let Some(t) = tail {
                path.push(PathStep::BlockTail);
                visit_expr(t, inout_params, fn_param_sigs, path, sites);
                path.pop();
            }
        }
        ExprKind::Call { callee, args, .. } => {
            // Check for swappable same-type `in` arguments when calling a known
            // module function.
            if let ExprKind::Name(callee_name) = &callee.kind
                && let Some(param_sigs) = fn_param_sigs.get(callee_name)
                && param_sigs.len() == args.len()
            {
                for i in 0..args.len() {
                    for j in (i + 1)..args.len() {
                        if param_sigs[i].0 == Pass::In
                            && param_sigs[j].0 == Pass::In
                            && args[i].pass == Pass::In
                            && args[j].pass == Pass::In
                            && param_sigs[i].1 == param_sigs[j].1
                            && args[i].expr != args[j].expr
                        {
                            sites.push(MutationSite {
                                path: path.clone(),
                                patch: Patch::SwapCallArgs(i, j),
                                kind: MutationKind::SwappedInArgs,
                                description: format!(
                                    "swap in args {i} and {j} in call to '{callee_name}'"
                                ),
                                span: expr.span.clone(),
                            });
                        }
                    }
                }
            }
            path.push(PathStep::CallCallee);
            visit_expr(callee, inout_params, fn_param_sigs, path, sites);
            path.pop();
            for (idx, arg) in args.iter().enumerate() {
                path.push(PathStep::CallArg(idx));
                visit_expr(&arg.expr, inout_params, fn_param_sigs, path, sites);
                path.pop();
            }
        }
        ExprKind::If {
            condition,
            then,
            otherwise,
        } => {
            path.push(PathStep::IfCond);
            visit_expr(condition, inout_params, fn_param_sigs, path, sites);
            path.pop();
            path.push(PathStep::IfThen);
            visit_expr(then, inout_params, fn_param_sigs, path, sites);
            path.pop();
            if let Some(el) = otherwise {
                path.push(PathStep::IfElse);
                visit_expr(el, inout_params, fn_param_sigs, path, sites);
                path.pop();
            }
        }
        ExprKind::Assign(_, _, rhs) => {
            path.push(PathStep::AssignRhs);
            visit_expr(rhs, inout_params, fn_param_sigs, path, sites);
            path.pop();
        }
        ExprKind::Tuple(es) => {
            for (i, e) in es.iter().enumerate() {
                path.push(PathStep::TupleElem(i));
                visit_expr(e, inout_params, fn_param_sigs, path, sites);
                path.pop();
            }
        }
        ExprKind::Struct { fields, .. } => {
            for (i, (_, e)) in fields.iter().enumerate() {
                path.push(PathStep::StructField(i));
                visit_expr(e, inout_params, fn_param_sigs, path, sites);
                path.pop();
            }
        }
        ExprKind::Field(base, _) => {
            path.push(PathStep::FieldBase);
            visit_expr(base, inout_params, fn_param_sigs, path, sites);
            path.pop();
        }
        ExprKind::Index(base, idx) => {
            path.push(PathStep::IndexBase);
            visit_expr(base, inout_params, fn_param_sigs, path, sites);
            path.pop();
            path.push(PathStep::IndexIdx);
            visit_expr(idx, inout_params, fn_param_sigs, path, sites);
            path.pop();
        }
        ExprKind::Try(inner) => {
            path.push(PathStep::TryInner);
            visit_expr(inner, inout_params, fn_param_sigs, path, sites);
            path.pop();
        }
        ExprKind::Match { value, arms } => {
            path.push(PathStep::MatchVal);
            visit_expr(value, inout_params, fn_param_sigs, path, sites);
            path.pop();
            for (i, (_, arm)) in arms.iter().enumerate() {
                path.push(PathStep::MatchArm(i));
                visit_expr(arm, inout_params, fn_param_sigs, path, sites);
                path.pop();
            }
        }
        ExprKind::Loop(body) => {
            path.push(PathStep::LoopBody);
            visit_expr(body, inout_params, fn_param_sigs, path, sites);
            path.pop();
        }
        ExprKind::For { iter, body, .. } => {
            path.push(PathStep::ForIter);
            visit_expr(iter, inout_params, fn_param_sigs, path, sites);
            path.pop();
            path.push(PathStep::ForBody);
            visit_expr(body, inout_params, fn_param_sigs, path, sites);
            path.pop();
        }
        ExprKind::Break(Some(val)) => {
            path.push(PathStep::BreakVal);
            visit_expr(val, inout_params, fn_param_sigs, path, sites);
            path.pop();
        }
        ExprKind::Return(Some(val)) => {
            path.push(PathStep::ReturnVal);
            visit_expr(val, inout_params, fn_param_sigs, path, sites);
            path.pop();
        }
        ExprKind::Closure { body, .. } => {
            path.push(PathStep::ClosureBody);
            visit_expr(body, inout_params, fn_param_sigs, path, sites);
            path.pop();
        }
        _ => {}
    }
}

fn mutate_binary_op(op: &str) -> Option<(&'static str, MutationKind)> {
    match op {
        "<" => Some(("<=", MutationKind::BoundaryFlip)),
        "<=" => Some(("<", MutationKind::BoundaryFlip)),
        ">" => Some((">=", MutationKind::BoundaryFlip)),
        ">=" => Some((">", MutationKind::BoundaryFlip)),
        "+" => Some(("-", MutationKind::ArithmeticSwap)),
        "-" => Some(("+", MutationKind::ArithmeticSwap)),
        "*" => Some(("+", MutationKind::ArithmeticSwap)),
        "/" => Some(("*", MutationKind::ArithmeticSwap)),
        "%" => Some(("/", MutationKind::ArithmeticSwap)),
        "==" => Some(("!=", MutationKind::EqualityFlip)),
        "!=" => Some(("==", MutationKind::EqualityFlip)),
        "&&" => Some(("||", MutationKind::LogicalFlip)),
        "||" => Some(("&&", MutationKind::LogicalFlip)),
        _ => None,
    }
}

fn apply_site(root: &mut Expr, path: &[PathStep], patch: &Patch) -> bool {
    let mut cur = root;
    for step in path {
        cur = match (step, &mut cur.kind) {
            (PathStep::BlockStmt(i), ExprKind::Block { statements, .. }) => {
                match statements.get_mut(*i) {
                    Some(Statement::Let { value, .. }) => value,
                    Some(Statement::Expr(e)) => e,
                    None => return false,
                }
            }
            (PathStep::BlockTail, ExprKind::Block { tail: Some(t), .. }) => t,
            (PathStep::IfCond, ExprKind::If { condition, .. }) => condition,
            (PathStep::IfThen, ExprKind::If { then, .. }) => then,
            (
                PathStep::IfElse,
                ExprKind::If {
                    otherwise: Some(el),
                    ..
                },
            ) => el,
            (PathStep::BinaryLhs, ExprKind::Binary(_, lhs, _)) => lhs,
            (PathStep::BinaryRhs, ExprKind::Binary(_, _, rhs)) => rhs,
            (PathStep::UnaryInner, ExprKind::Unary(_, inner)) => inner,
            (PathStep::CallCallee, ExprKind::Call { callee, .. }) => callee,
            (PathStep::CallArg(i), ExprKind::Call { args, .. }) => match args.get_mut(*i) {
                Some(Arg { expr, .. }) => expr,
                None => return false,
            },
            (PathStep::AssignRhs, ExprKind::Assign(_, _, rhs)) => rhs,
            (PathStep::TupleElem(i), ExprKind::Tuple(es)) => match es.get_mut(*i) {
                Some(e) => e,
                None => return false,
            },
            (PathStep::StructField(i), ExprKind::Struct { fields, .. }) => {
                match fields.get_mut(*i) {
                    Some((_, e)) => e,
                    None => return false,
                }
            }
            (PathStep::FieldBase, ExprKind::Field(base, _)) => base,
            (PathStep::IndexBase, ExprKind::Index(base, _)) => base,
            (PathStep::IndexIdx, ExprKind::Index(_, idx)) => idx,
            (PathStep::TryInner, ExprKind::Try(inner)) => inner,
            (PathStep::MatchVal, ExprKind::Match { value, .. }) => value,
            (PathStep::MatchArm(i), ExprKind::Match { arms, .. }) => match arms.get_mut(*i) {
                Some((_, arm)) => arm,
                None => return false,
            },
            (PathStep::LoopBody, ExprKind::Loop(body)) => body,
            (PathStep::ForIter, ExprKind::For { iter, .. }) => iter,
            (PathStep::ForBody, ExprKind::For { body, .. }) => body,
            (PathStep::BreakVal, ExprKind::Break(Some(v))) => v,
            (PathStep::ReturnVal, ExprKind::Return(Some(v))) => v,
            (PathStep::ClosureBody, ExprKind::Closure { body, .. }) => body,
            _ => return false,
        };
    }

    match (patch, &mut cur.kind) {
        (Patch::BinaryOp(new_op), ExprKind::Binary(op, _, _)) => {
            *op = (*new_op).to_string();
            true
        }
        (Patch::FlipBool(v), ExprKind::Literal(Literal::Bool(b))) => {
            *b = *v;
            true
        }
        (Patch::RemoveUnaryNot, ExprKind::Unary(_, inner)) => {
            let replacement = (**inner).clone();
            *cur = replacement;
            true
        }
        (Patch::DropBlockStmt(idx), ExprKind::Block { statements, .. }) => {
            if *idx < statements.len() {
                statements.remove(*idx);
                true
            } else {
                false
            }
        }
        (Patch::SwapCallArgs(i, j), ExprKind::Call { args, .. })
            if *i < args.len() && *j < args.len() =>
        {
            args.swap(*i, *j);
            true
        }
        _ => false,
    }
}

