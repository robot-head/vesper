    #[test]
    fn hot_swap_jit_executes_baseline_and_mutants_in_single_module() {
        let src = r#"
fn add(a: i64, b: i64) -> i64 eff [Fail[ArithOverflow]] {
    a + b
}
fn test_add() -> i64 eff [Fail[ArithOverflow]] {
    add(10, 5)
}
"#;
        let (module, world) = parse_and_check(src);
        let test_names: BTreeSet<String> = ["test_add".to_string()].into_iter().collect();
        let ast_mutants = collect_ast_mutants(&module, &test_names, 16);
        assert_eq!(ast_mutants.len(), 1);
        assert_eq!(ast_mutants[0].fn_name, "add");
        assert_eq!(ast_mutants[0].kind, MutationKind::ArithmeticSwap);

        let variants: Vec<MutantVariant> = ast_mutants
            .iter()
            .enumerate()
            .map(|(idx, m)| m.to_variant(idx))
            .collect();

        let session = HotSwapJitSession::compile(
            &world,
            &["test_add".to_string()],
            &variants,
            BatchLimits::default(),
        )
        .expect("compile hot-swap JIT session");

        let stats = session.stats();
        assert_eq!(stats.module_count, 1);
        assert_eq!(stats.dispatch_slots, 1);
        assert_eq!(stats.mutant_functions, 1);

        // Baseline: 10 + 5 = 15
        let base = session.run_entry("test_add").expect("baseline run");
        assert!(matches!(base, Value::Int(15)), "got {base}");

        // Mutant 0 (`+` -> `-`): 10 - 5 = 5
        let mutated = session
            .with_mutant("add", 0, || session.run_entry("test_add"))
            .expect("with_mutant")
            .expect("mutant run");
        assert!(matches!(mutated, Value::Int(5)), "got {mutated}");

        // Automatically restored to baseline: 10 + 5 = 15
        let restored = session.run_entry("test_add").expect("restored run");
        assert!(matches!(restored, Value::Int(15)), "got {restored}");
    }

