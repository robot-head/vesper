//! Pure Lean extraction. Mutable parameters become explicit returned state;
//! unhandled effects become monadic evidence parameters rather than axioms.
use crate::{ast::*, check::World};
use std::collections::BTreeMap;
pub(crate) fn name(s: &str) -> String {
    format!("«{}»", s.replace('»', "_"))
}
fn adt_groups(world: &World) -> Vec<Vec<&Adt>> {
    fn dependencies<'a>(t: &'a Type, names: &mut Vec<&'a str>) {
        match t {
            Type::Named(n, ts) => {
                names.push(n);
                for t in ts {
                    dependencies(t, names);
                }
            }
            Type::Tuple(ts) => {
                for t in ts {
                    dependencies(t, names);
                }
            }
            Type::Function { params, result, .. } => {
                for (_, t) in params {
                    dependencies(t, names);
                }
                dependencies(result, names);
            }
            _ => {}
        }
    }
    let mut graph = petgraph::graphmap::DiGraphMap::<&str, ()>::new();
    for a in world
        .adts
        .values()
        .filter(|a| a.name != "Option" && a.name != "Result")
    {
        graph.add_node(&a.name);
    }
    for a in world.adts.values() {
        if !graph.contains_node(a.name.as_str()) {
            continue;
        }
        for field in a.variants.iter().flat_map(|v| &v.fields) {
            let mut names = vec![];
            dependencies(&field.ty, &mut names);
            for n in names {
                if graph.contains_node(n) {
                    graph.add_edge(a.name.as_str(), n, ());
                }
            }
        }
    }
    petgraph::algo::tarjan_scc(&graph)
        .into_iter()
        .map(|names| names.into_iter().map(|n| &world.adts[n]).collect())
        .collect()
}
pub fn extract(world: &World) -> Result<String, String> {
    let mut out = String::from(
        "import Std\n\n/- Generated by Vesper. No axioms or sorry placeholders.\n   Partial definitions are executable translations, not termination proofs. -/\nnamespace Vesper\n\n",
    );
    out.push_str("abbrev HandlerCPS (S O : Type) (m : Type → Type) (A : Type) := (A → S → m O) → S → m O\ninstance [Monad m] : Monad (HandlerCPS S O m) where\n  pure a := fun k s => k a s\n  bind action next := fun k s => action (fun a s' => next a k s') s\n\n");
    out.push_str("def liftAction [Monad m] (action : m A) : HandlerCPS S O m A := fun k s => do\n  let value ← action\n  k value s\n\n");
    for group in adt_groups(world) {
        out.push_str("mutual\n");
        for a in group {
            let gs = a
                .generics
                .iter()
                .filter(|g| !g.row)
                .map(|g| format!("({} : Type)", name(&g.name)))
                .collect::<Vec<_>>()
                .join(" ");
            if a.is_enum {
                out.push_str(&format!("inductive {} {gs} where\n", name(&a.name)));
                for v in &a.variants {
                    out.push_str(&format!("  | {}", name(&v.name)));
                    for f in &v.fields {
                        out.push_str(&format!(
                            " ({} : {})",
                            name(&format!("f{}", f.name)),
                            ty(&f.ty)?
                        ));
                    }
                    out.push('\n');
                }
            } else {
                out.push_str(&format!("structure {} {gs} where\n", name(&a.name)));
                for f in &a.variants[0].fields {
                    out.push_str(&format!("  {} : {}\n", name(&f.name), ty(&f.ty)?));
                }
            }
            out.push('\n');
        }
        out.push_str("end\n\n");
    }
    for e in world.effects.values() {
        out.push_str(&format!("class Effect_{}", e.name));
        for g in &e.generics {
            out.push_str(&format!(" ({} : Type)", name(&g.name)));
        }
        out.push_str(" (m : Type → Type) where\n");
        for op in &e.ops {
            out.push_str(&format!("  {} : ", name(&op.name)));
            for p in &op.params {
                out.push_str(&format!("{} → ", ty(&p.ty)?));
            }
            out.push_str(&format!("m ({})\n", ty(&op.result)?));
        }
        out.push('\n');
    }
    for effect in world.effects.values() {
        let gs = effect
            .generics
            .iter()
            .map(|g| format!(" {{{} : Type}}", name(&g.name)))
            .collect::<String>();
        let args = effect
            .generics
            .iter()
            .map(|g| name(&g.name))
            .collect::<Vec<_>>()
            .join(" ");
        out.push_str(&format!("def lift_{} {{S O : Type}} {{m : Type → Type}} [Monad m]{gs} (evidence : Effect_{} {args} m) : Effect_{} {args} (HandlerCPS S O m) where\n",effect.name,effect.name,effect.name));
        for op in &effect.ops {
            let ps = op
                .params
                .iter()
                .enumerate()
                .map(|(i, _)| name(&format!("$arg{i}")))
                .collect::<Vec<_>>();
            out.push_str(&format!("  {} := fun {} k s => do\n    let result ← Effect_{}.{} (self := evidence) {}\n    k result s\n",name(&op.name),ps.join(" "),effect.name,name(&op.name),ps.join(" ")));
        }
        out.push_str(&format!("instance [Monad m]{gs} [evidence : Effect_{} {args} m] : Effect_{} {args} (HandlerCPS S O m) := lift_{} evidence\n\n",effect.name,effect.name,effect.name));
    }
    // Lean needs callees declared before callers. Mutually recursive functions
    // are emitted in one mutual group, retaining explicit partiality.
    out.push_str("mutual\n");
    let program = crate::ir::lower_world(world);
    for f in world.functions.values() {
        if let Some(definitions) =
            crate::lean_ir::extract_function(world, &program.functions[&f.name])
        {
            out.push_str(&definitions?);
            continue;
        }
        let effectful = !f.effects.instances.is_empty() || f.effects.tail.is_some();
        let polymorphic = effectful
            || effectful_arrow(&f.result)
            || f.params.iter().any(|p| effectful_arrow(&p.ty));
        let mut generator = Generator {
            world,
            locals: BTreeMap::new(),
            local_depths: BTreeMap::new(),
            counter: 0,
            monad: if !polymorphic {
                "Id".into()
            } else {
                "m".into()
            },
            caps: BTreeMap::new(),
            layers: vec![],
            continuations: Default::default(),
        };
        out.push_str(&format!("  partial def {} ", name(&f.name)));
        for g in &f.generics {
            if !g.row {
                out.push_str(&format!("{{{} : Type}} ", name(&g.name)));
            }
        }
        if polymorphic {
            out.push_str("{m : Type → Type} [Monad m] ");
            for (index, e) in function_requirements(f).iter().enumerate() {
                let variable = name(&format!("$cap{index}"));
                if let Some(label) = &e.label {
                    generator.caps.insert(
                        label.clone(),
                        CapBinding {
                            effect: e.clone(),
                            term: variable.clone(),
                            depth: 0,
                        },
                    );
                }
                out.push_str(&format!(
                    "[{variable} : Effect_{} {} m] ",
                    e.name,
                    e.args
                        .iter()
                        .map(ty)
                        .collect::<Result<Vec<_>, _>>()?
                        .join(" ")
                ));
            }
        }
        for p in &f.params {
            out.push_str(&format!("({} : {}) ", name(&p.name), generator.ty(&p.ty)?));
            generator.locals.insert(p.name.clone(), p.ty.clone());
            generator.local_depths.insert(p.name.clone(), 0);
        }
        let states = f
            .params
            .iter()
            .filter(|p| p.pass == Pass::Inout)
            .collect::<Vec<_>>();
        let mut result = generator.ty(&f.result)?;
        if !states.is_empty() {
            result = format!(
                "({result} × {})",
                states
                    .iter()
                    .map(|p| generator.ty(&p.ty))
                    .collect::<Result<Vec<_>, _>>()?
                    .join(" × ")
            );
        }
        if effectful {
            out.push_str(&format!(": m ({result}) := do\n"));
        } else {
            out.push_str(&format!(": {result} := Id.run do\n"));
        }
        for p in &f.params {
            out.push_str(&format!(
                "    let mut {} := {}\n",
                name(&p.name),
                name(&p.name)
            ));
        }
        let body = f.body.as_ref().ok_or("missing function body")?;
        let body = if let ExprKind::Block { statements, tail } = &body.kind {
            for s in statements {
                out.push_str(&generator.statement(s, 4)?);
            }
            tail.as_ref()
                .map(|e| generator.expr(e, 4))
                .transpose()?
                .unwrap_or_else(|| "()".into())
        } else {
            generator.expr(body, 4)?
        };
        out.push_str(&format!(
            "    let __result : {} := {body}\n",
            generator.ty(&f.result)?
        ));
        if states.is_empty() {
            out.push_str("    pure __result\n");
        } else {
            out.push_str(&format!(
                "    pure (__result, {})\n",
                states
                    .iter()
                    .map(|p| name(&p.name))
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
        }
        out.push('\n');
    }
    out.push_str("end\n\nend Vesper\n");
    Ok(out)
}
fn function_requirements(f: &Function) -> Vec<Effect> {
    fn visit(t: &Type, effects: &mut Vec<Effect>) {
        match t {
            Type::Function {
                result,
                effects: row,
                ..
            } => {
                for e in &row.instances {
                    if !effects.contains(e) {
                        effects.push(e.clone());
                    }
                }
                visit(result, effects);
            }
            Type::Named(_, ts) | Type::Tuple(ts) => {
                for t in ts {
                    visit(t, effects);
                }
            }
            _ => (),
        }
    }
    let mut effects = f.effects.instances.clone();
    visit(&f.result, &mut effects);
    effects
}
pub(crate) fn ty(t: &Type) -> Result<String, String> {
    typed(t, None)
}
pub(crate) fn ty_monad(t: &Type, monad: &str) -> Result<String, String> {
    typed(t, Some(monad))
}
pub(crate) fn effectful_arrow(t: &Type) -> bool {
    match t {
        Type::Function {
            params,
            result,
            effects,
            ..
        } => {
            !effects.instances.is_empty()
                || effects.tail.is_some()
                || params.iter().any(|(_, t)| effectful_arrow(t))
                || effectful_arrow(result)
        }
        Type::Named(_, ts) | Type::Tuple(ts) => ts.iter().any(effectful_arrow),
        _ => false,
    }
}
fn typed(t: &Type, monad: Option<&str>) -> Result<String, String> {
    Ok(match t {
        Type::IntLiteral(n) => typed(&crate::numeric::IntegerKind::default_for(*n).ty(), monad)?,
        Type::Named(n, args) => {
            let n = match n.as_str() {
                "u8" => "UInt8".into(),
                "u32" => "UInt32".into(),
                "u64" => "UInt64".into(),
                "i64" => "Int64".into(),
                "f64" => "Float".into(),
                "bool" => "Bool".into(),
                "Unit" => "Unit".into(),
                "Never" => "Empty".into(),
                "String" => "String".into(),
                "Option" => "Option".into(),
                "Result" => "Except".into(),
                _ => name(n),
            };
            let args = if t.name() == "Result" && args.len() == 2 {
                vec![&args[1], &args[0]]
            } else {
                args.iter().collect()
            };
            if args.is_empty() {
                n
            } else {
                format!(
                    "({n} {})",
                    args.into_iter()
                        .map(|t| typed(t, monad))
                        .collect::<Result<Vec<_>, _>>()?
                        .join(" ")
                )
            }
        }
        Type::Tuple(ts) => {
            if ts.is_empty() {
                "Unit".into()
            } else {
                format!(
                    "({})",
                    ts.iter()
                        .map(|t| typed(t, monad))
                        .collect::<Result<Vec<_>, _>>()?
                        .join(" × ")
                )
            }
        }
        Type::Function {
            params,
            result,
            effects,
            ..
        } => {
            let mut results = vec![typed(result, monad)?];
            results.extend(
                params
                    .iter()
                    .filter(|(p, _)| *p == Pass::Inout)
                    .map(|(_, t)| typed(t, monad))
                    .collect::<Result<Vec<_>, _>>()?,
            );
            let result = if results.len() == 1 {
                results[0].clone()
            } else {
                format!("({})", results.join(" × "))
            };
            let args = if params.is_empty() {
                String::from("Unit → ")
            } else {
                params
                    .iter()
                    .map(|(_, t)| typed(t, monad).map(|t| format!("{t} → ")))
                    .collect::<Result<String, _>>()?
            };
            let result = if !effects.instances.is_empty() || effects.tail.is_some() {
                format!(
                    "{} ({result})",
                    monad.ok_or("effectful function type needs an ambient Lean monad")?
                )
            } else {
                result
            };
            format!("({args}{result})")
        }
        Type::Infer => "_".into(),
        Type::Row(_) => return Err("effect rows are not first-class Lean values".into()),
    })
}
struct Generator<'a> {
    world: &'a World,
    locals: BTreeMap<String, Type>,
    local_depths: BTreeMap<String, usize>,
    counter: usize,
    monad: String,
    caps: BTreeMap<String, CapBinding>,
    layers: Vec<(String, String, String)>,
    continuations: std::collections::BTreeSet<String>,
}
#[derive(Clone)]
struct CapBinding {
    effect: Effect,
    term: String,
    depth: usize,
}
impl Generator<'_> {
    fn ty(&self, t: &Type) -> Result<String, String> {
        ty_monad(t, &self.monad)
    }
    fn lift_action(&self, mut action: String, depth: usize) -> String {
        for (state, output, _) in self.layers.iter().skip(depth) {
            action = format!("(liftAction (S := {state}) (O := {output}) {action})");
        }
        action
    }
    fn adapt_callable(&self, value: String, t: &Type, depth: usize) -> Result<String, String> {
        if depth >= self.layers.len() {
            return Ok(value);
        }
        let Type::Function {
            params, effects, ..
        } = t
        else {
            return Ok(value);
        };
        if effects.instances.is_empty() && effects.tail.is_none() {
            return Ok(value);
        }
        let args = if params.is_empty() {
            vec!["«$unit»".to_string()]
        } else {
            (0..params.len()).map(|i| format!("«$arg{i}»")).collect()
        };
        let call = format!("({value} {})", args.join(" "));
        Ok(format!(
            "(fun {} => {})",
            args.join(" "),
            self.lift_action(call, depth)
        ))
    }
    fn closure(
        &mut self,
        e: &Expr,
        params: &[Param],
        body: &Expr,
        indent: usize,
    ) -> Result<String, String> {
        let Some(Type::Function {
            params: typed_params,
            result,
            effects,
            ..
        }) = self.world.types.get(&(e.span.start, e.span.end)).cloned()
        else {
            return Err("closure lacks its checked arrow type".into());
        };
        let effectful = !effects.instances.is_empty() || effects.tail.is_some();
        let mut captures = crate::check::free_names(body);
        for p in params {
            captures.remove(&p.name);
        }
        let captures = captures
            .into_iter()
            .filter(|n| self.locals.contains_key(n))
            .collect::<Vec<_>>();
        self.counter += 1;
        let id = self.counter;
        let pad = " ".repeat(indent);
        let mut text = String::from("(← do\n");
        for (index, n) in captures.iter().enumerate() {
            text.push_str(&format!(
                "{pad}  let «$capture{id}_{index}» := {}\n",
                name(n)
            ));
        }
        let arguments = if params.is_empty() {
            "(_ : Unit)".into()
        } else {
            params
                .iter()
                .zip(&typed_params)
                .map(|(p, (_, t))| self.ty(t).map(|t| format!("({} : {t})", name(&p.name))))
                .collect::<Result<Vec<_>, _>>()?
                .join(" ")
        };
        text.push_str(&format!(
            "{pad}  pure (fun {arguments} => {}do\n",
            if effectful { "" } else { "Id.run " }
        ));
        let locals = self.locals.clone();
        let depths = self.local_depths.clone();
        let monad = self.monad.clone();
        if !effectful {
            self.monad = "Id".into();
        }
        for (index, n) in captures.iter().enumerate() {
            text.push_str(&format!(
                "{pad}    let mut {} := «$capture{id}_{index}»\n",
                name(n)
            ));
        }
        for (p, (_, t)) in params.iter().zip(&typed_params) {
            self.locals.insert(p.name.clone(), t.clone());
            self.local_depths.insert(p.name.clone(), self.layers.len());
            text.push_str(&format!(
                "{pad}    let mut {} := {}\n",
                name(&p.name),
                name(&p.name)
            ));
        }
        let value = if let ExprKind::Block { statements, tail } = &body.kind {
            for s in statements {
                text.push_str(&self.statement(s, indent + 4)?);
            }
            tail.as_ref()
                .map(|e| self.expr(e, indent + 4))
                .transpose()?
                .unwrap_or_else(|| "()".into())
        } else {
            self.expr(body, indent + 4)?
        };
        text.push_str(&format!(
            "{pad}    let result : {} := {value}\n",
            self.ty(&result)?
        ));
        let states = params
            .iter()
            .zip(&typed_params)
            .filter(|(_, (p, _))| *p == Pass::Inout)
            .map(|(p, _)| name(&p.name))
            .collect::<Vec<_>>();
        text.push_str(&format!(
            "{pad}    pure {}))",
            if states.is_empty() {
                "result".into()
            } else {
                format!("(result, {})", states.join(", "))
            }
        ));
        self.locals = locals;
        self.local_depths = depths;
        self.monad = monad;
        Ok(text)
    }

    fn evidence(&self, cap: &CapBinding) -> String {
        let mut term = cap.term.clone();
        for (state, output, base) in self.layers.iter().skip(cap.depth) {
            term = format!(
                "(lift_{} (S := {state}) (O := {output}) (m := {base}) {term})",
                cap.effect.name
            );
        }
        term
    }
    fn register_pattern(&mut self, p: &Pattern, t: &Type) {
        match &p.kind {
            PatternKind::Bind(n) => {
                self.locals.insert(n.clone(), t.clone());
                self.local_depths.insert(n.clone(), self.layers.len());
            }
            PatternKind::Tuple(ps) => {
                if let Type::Tuple(ts) = t {
                    for (p, t) in ps.iter().zip(ts) {
                        self.register_pattern(p, t);
                    }
                }
            }
            PatternKind::Constructor { name, fields, .. } => {
                if let Some((a, v)) = self.world.constructor(name) {
                    let args = if let Type::Named(_, ts) = t {
                        ts.clone()
                    } else {
                        vec![]
                    };
                    let vars = a
                        .generics
                        .iter()
                        .zip(args)
                        .map(|(g, t)| (g.name.clone(), t))
                        .collect();
                    let fields = fields
                        .iter()
                        .filter_map(|(n, p)| {
                            v.fields
                                .iter()
                                .find(|f| &f.name == n)
                                .map(|f| (p, substitute(&f.ty, &vars)))
                        })
                        .collect::<Vec<_>>();
                    for (p, t) in fields {
                        self.register_pattern(p, &t);
                    }
                }
            }
            _ => {}
        }
    }
    fn bind_text(
        &mut self,
        p: &Pattern,
        t: &Type,
        value: &str,
        indent: usize,
    ) -> Result<String, String> {
        let pad = " ".repeat(indent);
        self.register_pattern(p, t);
        if let PatternKind::Bind(n) = &p.kind {
            return Ok(format!("{pad}let mut {} := {value}\n", name(n)));
        }
        Ok(format!("{pad}let {} := {value}\n", self.pat(p)?))
    }
    fn body_text(&mut self, e: &Expr, indent: usize) -> Result<String, String> {
        let pad = " ".repeat(indent);
        let mut text = String::new();
        let result = if let ExprKind::Block { statements, tail } = &e.kind {
            for s in statements {
                text.push_str(&self.statement(s, indent)?);
            }
            if let Some(t) = tail {
                self.expr(t, indent)?
            } else {
                "()".into()
            }
        } else {
            self.expr(e, indent)?
        };
        text.push_str(&format!("{pad}pure {result}\n"));
        Ok(text)
    }
    #[expect(
        clippy::too_many_arguments,
        reason = "The inputs mirror the lexical handler judgment"
    )]
    fn handler(
        &mut self,
        e: &Expr,
        effect: &Effect,
        state: &Option<(Pattern, Box<Expr>)>,
        body: &Expr,
        ret: &Clause,
        ops: &[Clause],
        indent: usize,
    ) -> Result<String, String> {
        self.counter += 1;
        let id = self.counter;
        let init = name(&format!("$init{id}"));
        let returned = name(&format!("$return{id}"));
        let dictionary = name(&format!("$handler{id}"));
        let computation = name(&format!("$body{id}"));
        let result_arg = name(&format!("$result{id}"));
        let state_arg = name(&format!("$state{id}"));
        let continuation = name(&format!("$resume{id}"));
        let outer_locals = self.locals.clone();
        let outer_depths = self.local_depths.clone();
        let outer_caps = self.caps.clone();
        let outer_continuations = self.continuations.clone();
        let parent = self.monad.clone();
        let body_type = crate::numeric::default_type(
            self.world
                .types
                .get(&(body.span.start, body.span.end))
                .ok_or("handler body lacks a type")?,
        );
        let output = self.ty(self
            .world
            .types
            .get(&(e.span.start, e.span.end))
            .ok_or("handler lacks an output type")?)?;
        let state_type = state
            .as_ref()
            .and_then(|(_, s)| self.world.types.get(&(s.span.start, s.span.end)))
            .map(crate::numeric::default_type)
            .unwrap_or_else(Type::unit);
        let st = self.ty(&state_type)?;
        let bt = self.ty(&body_type)?;
        let child = format!("(HandlerCPS {st} {output} {parent})");
        let args = effect
            .args
            .iter()
            .map(|t| self.ty(t))
            .collect::<Result<Vec<_>, _>>()?
            .join(" ");
        let initial = state
            .as_ref()
            .map(|(_, s)| self.expr(s, indent + 2))
            .transpose()?
            .unwrap_or_else(|| "()".into());
        let pad = " ".repeat(indent);
        let inner = " ".repeat(indent + 2);
        let field = " ".repeat(indent + 4);
        let mut text = format!(
            "(← do\n{inner}let {init} : {st} := {initial}\n{inner}let {returned} : {bt} → {st} → {parent} {output} := fun {result_arg} {state_arg} => do\n"
        );
        let return_type = if state.is_some() {
            Type::Tuple(vec![body_type.clone(), state_type.clone()])
        } else {
            body_type.clone()
        };
        let return_value = if state.is_some() {
            format!("({result_arg}, {state_arg})")
        } else {
            result_arg.clone()
        };
        text.push_str(&self.bind_text(&ret.pats[0], &return_type, &return_value, indent + 4)?);
        text.push_str(&self.body_text(&ret.body, indent + 4)?);
        self.locals = outer_locals.clone();
        self.local_depths = outer_depths.clone();
        text.push_str(&format!(
            "{inner}let {dictionary} : Effect_{} {args} {child} := {{\n",
            effect.name
        ));
        let decl = self
            .world
            .effects
            .get(&effect.name)
            .ok_or("unknown Lean effect")?
            .clone();
        let vars = decl
            .generics
            .iter()
            .zip(&effect.args)
            .map(|(g, t)| (g.name.clone(), t.clone()))
            .collect();
        for clause in ops {
            let sig = decl
                .ops
                .iter()
                .find(|f| f.name == clause.name)
                .ok_or("unknown Lean operation")?;
            if sig.params.iter().any(|p| p.pass == Pass::Inout) {
                return Err(
                    "Lean handler inout operations require state-passing operation evidence".into(),
                );
            }
            let parameters = sig
                .params
                .iter()
                .enumerate()
                .map(|(i, p)| {
                    self.ty(&substitute(&p.ty, &vars))
                        .map(|t| format!("({} : {t})", name(&format!("$op{id}_{i}"))))
                })
                .collect::<Result<Vec<_>, _>>()?
                .join(" ");
            text.push_str(&format!(
                "{field}{} := fun {parameters} {continuation} {state_arg} => do\n",
                name(&clause.name)
            ));
            let capture_names = crate::check::clause_free_names(clause);
            for n in capture_names
                .iter()
                .filter(|n| outer_locals.contains_key(*n))
            {
                text.push_str(&format!("{field}  let mut {} := {}\n", name(n), name(n)));
            }
            for (i, (p, param)) in clause.pats.iter().zip(&sig.params).enumerate() {
                text.push_str(&self.bind_text(
                    p,
                    &substitute(&param.ty, &vars),
                    &name(&format!("$op{id}_{i}")),
                    indent + 6,
                )?);
            }
            let mut index = sig.params.len();
            if state.is_some() {
                text.push_str(&self.bind_text(
                    &clause.pats[index],
                    &state_type,
                    &state_arg,
                    indent + 6,
                )?);
                index += 1;
            }
            let result_type = self.ty(&substitute(&sig.result, &vars))?;
            let resume_value = if state.is_some() {
                format!(
                    "(fun (value : {result_type}) (state : {st}) => {continuation} value state)"
                )
            } else {
                format!("(fun (value : {result_type}) => {continuation} value ())")
            };
            if let PatternKind::Bind(k) = &clause.pats[index].kind {
                self.continuations.insert(k.clone());
                text.push_str(&format!("{field}  let {} := {resume_value}\n", name(k)));
            }
            text.push_str(&self.body_text(&clause.body, indent + 6)?);
            self.locals = outer_locals.clone();
            self.local_depths = outer_depths.clone();
            self.continuations = outer_continuations.clone();
        }
        text.push_str(&format!("{inner}}}\n{inner}letI : Effect_{} {args} {child} := {dictionary}\n{inner}let {computation} : {child} {bt} := do\n",effect.name));
        self.layers.push((st, output, parent));
        self.monad = child;
        if let Some(label) = &effect.label {
            self.caps.insert(
                label.clone(),
                CapBinding {
                    effect: effect.clone(),
                    term: dictionary,
                    depth: self.layers.len(),
                },
            );
        }
        text.push_str(&self.body_text(body, indent + 4)?);
        text.push_str(&format!("{inner}{computation} {returned} {init}\n{pad})"));
        self.monad = self.layers.pop().unwrap().2;
        self.locals = outer_locals;
        self.local_depths = outer_depths;
        self.caps = outer_caps;
        self.continuations = outer_continuations;
        Ok(text)
    }
    fn pat(&self, p: &Pattern) -> Result<String, String> {
        Ok(match &p.kind {
            PatternKind::Wild => "_".into(),
            PatternKind::Bind(n) => name(n),
            PatternKind::Literal(l) => literal(l),
            PatternKind::Tuple(ps) => format!(
                "({})",
                ps.iter()
                    .map(|p| self.pat(p))
                    .collect::<Result<Vec<_>, _>>()?
                    .join(", ")
            ),
            PatternKind::Constructor {
                name: n,
                fields,
                named,
            } => {
                let c = self.constructor(n)?;
                if *named {
                    format!(
                        "{{ {} }}",
                        fields
                            .iter()
                            .map(|(n, p)| self.pat(p).map(|p| format!("{} := {p}", name(n))))
                            .collect::<Result<Vec<_>, _>>()?
                            .join(", ")
                    )
                } else if fields.is_empty() {
                    c
                } else {
                    format!(
                        "({c} {})",
                        fields
                            .iter()
                            .map(|(_, p)| self.pat(p))
                            .collect::<Result<Vec<_>, _>>()?
                            .join(" ")
                    )
                }
            }
        })
    }
    fn constructor(&self, n: &str) -> Result<String, String> {
        Ok(match n {
            "Ok" => "Except.ok".into(),
            "Err" => "Except.error".into(),
            "Some" => "Option.some".into(),
            "None" => "Option.none".into(),
            _ => {
                let (a, v) = self
                    .world
                    .constructor(n)
                    .ok_or("unknown Lean constructor")?;
                if a.is_enum {
                    format!("{}.{}", name(&a.name), name(&v.name))
                } else {
                    format!("{}.mk", name(&a.name))
                }
            }
        })
    }
    fn expr(&mut self, e: &Expr, indent: usize) -> Result<String, String> {
        let pad = " ".repeat(indent);
        let text = match &e.kind {
            ExprKind::Literal(l) => {
                let text = literal(l);
                if let Some(t) = self.world.types.get(&(e.span.start, e.span.end)) {
                    format!("({text} : {})", self.ty(&crate::numeric::default_type(t))?)
                } else {
                    text
                }
            }
            ExprKind::Name(n) => {
                if self.world.constructor(n).is_some() {
                    self.constructor(n)?
                } else if let Some(t) = self.locals.get(n) {
                    self.adapt_callable(
                        name(n),
                        t,
                        self.local_depths
                            .get(n)
                            .copied()
                            .unwrap_or(self.layers.len()),
                    )?
                } else if !self.locals.contains_key(n)
                    && self
                        .world
                        .functions
                        .get(n)
                        .is_some_and(|f| f.params.is_empty())
                {
                    format!("(fun (_ : Unit) => {})", name(n))
                } else {
                    name(n)
                }
            }
            ExprKind::Tuple(es) => {
                if es.is_empty() {
                    "()".into()
                } else {
                    format!(
                        "({})",
                        es.iter()
                            .map(|e| self.expr(e, indent))
                            .collect::<Result<Vec<_>, _>>()?
                            .join(", ")
                    )
                }
            }
            ExprKind::Struct { name: n, fields } => format!(
                "({{ {} }} : {})",
                fields
                    .iter()
                    .map(|(n, e)| self.expr(e, indent).map(|e| format!("{} := {e}", name(n))))
                    .collect::<Result<Vec<_>, _>>()?
                    .join(", "),
                name(n)
            ),
            ExprKind::Field(e, n) => format!("({}).{}", self.expr(e, indent)?, name(n)),
            ExprKind::Unary(op, e) => format!("({op}{})", self.expr(e, indent)?),
            ExprKind::Binary(op, a, b) => {
                let a = self.expr(a, indent)?;
                let b = self.expr(b, indent)?;
                if self.world.partial_ops.contains(&(e.span.start, e.span.end)) {
                    format!(
                        "(← do\n{pad}  let left := {a}\n{pad}  let right := {b}\n{pad}  if right == 0 then\n{pad}    let impossible ← Effect_Fail.«raise» «RuntimeError».«DivisionByZero»\n{pad}    nomatch impossible\n{pad}  else pure (left {op} right))"
                    )
                } else if matches!(op.as_str(), "<" | "<=" | ">" | ">=") {
                    format!("(decide ({a} {op} {b}))")
                } else {
                    format!("({a} {op} {b})")
                }
            }
            ExprKind::Assign(..) => {
                return Err("assignment must occur as a statement during Lean extraction".into());
            }
            ExprKind::Block { statements, tail } => {
                let mut s = String::from("(← do\n");
                for st in statements {
                    s.push_str(&self.statement(st, indent + 2)?);
                }
                let result = if let Some(t) = tail {
                    self.expr(t, indent + 2)?
                } else {
                    "()".into()
                };
                s.push_str(&format!("{pad}  pure {result})"));
                s
            }
            ExprKind::If {
                condition,
                then,
                otherwise,
            } => format!(
                "(← do\n{pad}  if {} then\n{pad}    pure {}\n{pad}  else\n{pad}    pure {})",
                self.expr(condition, indent)?,
                self.expr(then, indent)?,
                otherwise
                    .as_ref()
                    .map(|e| self.expr(e, indent))
                    .transpose()?
                    .unwrap_or_else(|| "()".into())
            ),
            ExprKind::Match { value, arms } => {
                let mut s = format!("(← do\n{pad}  match {} with\n", self.expr(value, indent)?);
                for (p, e) in arms {
                    s.push_str(&format!(
                        "{pad}  | {} => pure {}\n",
                        self.pat(p)?,
                        self.expr(e, indent + 2)?
                    ));
                }
                s.push_str(&format!("{pad})"));
                s
            }
            ExprKind::Call {
                callee,
                types,
                args,
            } => {
                if let ExprKind::Field(base, method) = &callee.kind
                    && let ExprKind::Name(local) = &base.kind
                    && let Some(t) = self.locals.get(local)
                {
                    let method_name = format!("{}::{method}", t.name());
                    if self.world.functions.contains_key(&method_name) {
                        let mut actual = vec![Arg {
                            pass: Pass::In,
                            explicit: false,
                            expr: *base.clone(),
                        }];
                        actual.extend(args.clone());
                        let call = Expr {
                            kind: ExprKind::Call {
                                callee: Box::new(Expr {
                                    kind: ExprKind::Name(method_name),
                                    span: callee.span.clone(),
                                }),
                                types: types.clone(),
                                args: actual,
                            },
                            span: e.span.clone(),
                        };
                        return self.expr(&call, indent);
                    }
                }
                if let ExprKind::Field(base, op) = &callee.kind
                    && let ExprKind::Name(label) = &base.kind
                    && let Some(cap) = self.caps.get(label).cloned()
                {
                    let evidence = self.evidence(&cap);
                    let values = args
                        .iter()
                        .map(|a| self.expr(&a.expr, indent))
                        .collect::<Result<Vec<_>, _>>()?
                        .join(" ");
                    return Ok(format!(
                        "(← Effect_{}.{} (self := {evidence}) {values})",
                        cap.effect.name,
                        name(op)
                    ));
                }
                let mut n = if let ExprKind::Name(n) = &callee.kind {
                    n.clone()
                } else {
                    return Err(
                        "Lean extraction of method and indirect calls requires named functions"
                            .into(),
                    );
                };
                let local_thunk = self
                    .locals
                    .get(&n)
                    .is_some_and(|t| matches!(t, Type::Function{params,..} if params.is_empty()));
                let callable_depth = self
                    .local_depths
                    .get(&n)
                    .copied()
                    .unwrap_or(self.layers.len());
                let mut effect = false;
                let mut evidence_args = String::new();
                if let Some(f) = self.world.functions.get(&n) {
                    for (index, e) in function_requirements(f).iter().enumerate() {
                        if let Some(label) = &e.label
                            && let Some(cap) = self.caps.get(label)
                        {
                            evidence_args.push_str(&format!(
                                " ({} := {})",
                                name(&format!("$cap{index}")),
                                self.evidence(cap)
                            ));
                        }
                    }
                }
                let continuation = self.continuations.contains(&n);
                if let Some((eff, op)) = n.split_once("::") {
                    if self.world.effects.contains_key(eff) {
                        n = format!("Effect_{eff}.{}", name(op));
                        effect = true;
                    } else {
                        n = name(&n);
                    }
                } else if self.world.constructor(&n).is_some() {
                    n = self.constructor(&n)?;
                } else {
                    effect = self.locals.get(&n).is_some_and(|t| matches!(t,Type::Function{effects,..} if !effects.instances.is_empty() || effects.tail.is_some())) || self.world.functions.get(&n).is_some_and(|f| {
                        !f.effects.instances.is_empty() || f.effects.tail.is_some()
                    });
                    if self
                        .world
                        .functions
                        .get(&n)
                        .is_some_and(|f| f.params.iter().any(|p| p.pass == Pass::Inout))
                    {
                        return Err("Lean inout calls require explicit state binding; extraction of callers is not yet available".into());
                    }
                    n = name(&n);
                }
                let type_args = if let ExprKind::Name(source) = &callee.kind {
                    if let Some(f) = self.world.functions.get(source) {
                        let solved = self.world.calls.get(&(e.span.start, e.span.end));
                        f.generics
                            .iter()
                            .filter(|g| !g.row)
                            .filter_map(|g| solved.and_then(|s| s.get(&g.name)).map(|t| (g, t)))
                            .map(|(g, t)| {
                                self.ty(t).map(|t| format!(" ({} := {t})", name(&g.name)))
                            })
                            .collect::<Result<String, _>>()?
                    } else {
                        String::new()
                    }
                } else {
                    String::new()
                };
                let mut values = args
                    .iter()
                    .map(|a| self.expr(&a.expr, indent))
                    .collect::<Result<Vec<_>, _>>()?
                    .join(" ");
                if args.is_empty() && local_thunk {
                    values = "()".into();
                }
                let call = format!("({n}{type_args}{evidence_args} {values})");
                if effect || continuation {
                    format!("(← {})", self.lift_action(call, callable_depth))
                } else {
                    call
                }
            }
            ExprKind::Closure { params, body, .. } => self.closure(e, params, body, indent)?,
            ExprKind::Handle {
                effect,
                state,
                body,
                ret,
                ops,
            } => self.handler(e, effect, state, body, ret, ops, indent)?,
            ExprKind::Try(v) => {
                let value = self.expr(v, indent + 2)?;
                format!(
                    "(← do\n{pad}  match {value} with\n{pad}  | Except.ok value => pure value\n{pad}  | Except.error error => do\n{pad}    let impossible ← Effect_Fail.«raise» error\n{pad}    nomatch impossible)"
                )
            }
            ExprKind::Index(base, index) => {
                let Some(Type::Tuple(ts)) = self.world.types.get(&(base.span.start, base.span.end))
                else {
                    return Err("Lean indexing requires a typed tuple".into());
                };
                if ts.is_empty() {
                    return Err("cannot extract indexing of an empty tuple".into());
                }
                let projection = |i: usize| {
                    format!(
                        "tuple{}{}",
                        ".2".repeat(i),
                        if i + 1 < ts.len() { ".1" } else { "" }
                    )
                };
                let mut body = if self.world.partial_ops.contains(&(e.span.start, e.span.end)) {
                    format!(
                        "do\n{pad}    let impossible ← Effect_Fail.«raise» «RuntimeError».«IndexOutOfBounds»\n{pad}    nomatch impossible"
                    )
                } else {
                    format!("pure ({})", projection(ts.len() - 1))
                };
                for i in (0..ts.len()).rev() {
                    body = format!("if index == {i} then pure ({}) else {body}", projection(i));
                }
                format!(
                    "(← do\n{pad}  let tuple := {}\n{pad}  let index := {}\n{pad}  {body})",
                    self.expr(base, indent)?,
                    self.expr(index, indent)?
                )
            }
        };
        Ok(
            if self
                .world
                .types
                .get(&(e.span.start, e.span.end))
                .is_some_and(|t| t.name() == "Never")
            {
                format!("(Empty.elim {text})")
            } else {
                text
            },
        )
    }
    fn statement(&mut self, st: &Statement, indent: usize) -> Result<String, String> {
        let pad = " ".repeat(indent);
        Ok(match st {
            Statement::Let { pat, ty: t, value } => {
                let val = self.expr(value, indent)?;
                let ann = if *t == Type::Infer {
                    String::new()
                } else {
                    format!(" : {}", self.ty(t)?)
                };
                if let PatternKind::Bind(n) = &pat.kind {
                    let inferred = if *t == Type::Infer {
                        if let Some(t) = self.world.types.get(&(value.span.start, value.span.end)) {
                            crate::numeric::default_type(t)
                        } else {
                            match &value.kind {
                                ExprKind::Struct { name, .. } => Type::named(name),
                                ExprKind::Literal(l) => crate::check::literal_type(l),
                                ExprKind::Name(n) => {
                                    self.locals.get(n).cloned().unwrap_or(Type::Infer)
                                }
                                _ => Type::Infer,
                            }
                        }
                    } else {
                        t.clone()
                    };
                    self.locals.insert(n.clone(), inferred.clone());
                    self.local_depths.insert(n.clone(), self.layers.len());
                    let ann = if ann.is_empty() && inferred != Type::Infer {
                        format!(" : {}", self.ty(&inferred)?)
                    } else {
                        ann
                    };
                    format!("{pad}let mut {}{ann} := {val}\n", name(n))
                } else {
                    format!("{pad}let {}{ann} := {val}\n", self.pat(pat)?)
                }
            }
            Statement::Expr(e) => {
                if let ExprKind::Call { callee, args, .. } = &e.kind
                    && let ExprKind::Name(n) = &callee.kind
                    && let Some(f) = self.world.functions.get(n)
                {
                    let states = f
                        .params
                        .iter()
                        .zip(args)
                        .filter(|(p, _)| p.pass == Pass::Inout)
                        .collect::<Vec<_>>();
                    if !states.is_empty() {
                        self.counter += 1;
                        let id = self.counter;
                        let vs = args
                            .iter()
                            .map(|a| self.expr(&a.expr, indent))
                            .collect::<Result<Vec<_>, _>>()?
                            .join(" ");
                        let call = format!("({} {vs})", name(n));
                        let call = if f.effects.instances.is_empty() && f.effects.tail.is_none() {
                            call
                        } else {
                            format!("(← {call})")
                        };
                        let names = (0..states.len())
                            .map(|i| format!("__state{id}_{i}"))
                            .collect::<Vec<_>>();
                        let mut text = format!("{pad}let (_, {}) := {call}\n", names.join(", "));
                        for ((_, a), new_state) in states.iter().zip(names) {
                            let p = crate::check::Place::from_expr(&a.expr)
                                .ok_or("inout argument needs a place")?;
                            text.push_str(&format!(
                                "{pad}{} := {}\n",
                                name(&p.root),
                                update_place(&p, &new_state)
                            ));
                        }
                        return Ok(text);
                    }
                }
                if let ExprKind::Assign(op, p, v) = &e.kind {
                    let value = self.expr(v, indent)?;
                    let p =
                        crate::check::Place::from_expr(p).ok_or("assignment requires a place")?;
                    let place = std::iter::once(name(&p.root))
                        .chain(p.path.iter().map(|p| name(p)))
                        .collect::<Vec<_>>()
                        .join(".");
                    let value = if op == "=" {
                        value
                    } else if self.world.partial_ops.contains(&(e.span.start, e.span.end)) {
                        format!(
                            "(← do\n{pad}  let right := {value}\n{pad}  if right == 0 then\n{pad}    let impossible ← Effect_Fail.«raise» «RuntimeError».«DivisionByZero»\n{pad}    nomatch impossible\n{pad}  else pure ({place} {} right))",
                            &op[..1]
                        )
                    } else {
                        format!("({place} {} {value})", &op[..1])
                    };
                    format!("{pad}{} := {}\n", name(&p.root), update_place(&p, &value))
                } else {
                    self.counter += 1;
                    let value = self.expr(e, indent)?;
                    format!("{pad}let _unused{} := {}\n", self.counter, value)
                }
            }
        })
    }
}
pub(crate) fn literal(l: &Literal) -> String {
    match l {
        Literal::Int(n) => n.to_string(),
        Literal::Float(n) => format!("({n:?} : Float)"),
        Literal::Bool(b) => b.to_string(),
        Literal::String(s) => serde_json::to_string(s).unwrap(),
    }
}

pub(crate) fn update_place(p: &crate::check::Place, value: &str) -> String {
    fn update(base: String, path: &[String], value: &str) -> String {
        if path.is_empty() {
            return value.into();
        }
        let field = name(&path[0]);
        let next = format!("{base}.{field}");
        format!(
            "{{ {base} with {field} := {} }}",
            update(next, &path[1..], value)
        )
    }
    update(name(&p.root), &p.path, value)
}
