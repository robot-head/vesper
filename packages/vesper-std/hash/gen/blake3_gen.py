# Generates packages/vesper-std/hash/src/compress.ves: the BLAKE3
# compression function, its 7 rounds unrolled into calls of the quarter
# round `g` with the message schedule applied to the arguments.
# `--straight-line` writes instead the 16-local version that is the repro of
# compiler gaps 1 and 6 in docs/parallel-results/self-host-std-data.md.
import sys

PERM = [2, 6, 3, 10, 7, 0, 4, 13, 1, 11, 12, 5, 9, 14, 15, 8]
G = [(0, 4, 8, 12), (1, 5, 9, 13), (2, 6, 10, 14), (3, 7, 11, 15),
     (0, 5, 10, 15), (1, 6, 11, 12), (2, 7, 8, 13), (3, 4, 9, 14)]
IV = [0x6A09E667, 0xBB67AE85, 0x3C6EF372, 0xA54FF53A]

out = []
w = out.append
w("// @vesper-std/hash::compress: the BLAKE3 compression function.")
w("//")
w("// Generated by packages/vesper-std/hash/gen/blake3_gen.py from the BLAKE3")
w("// reference implementation; do not edit by hand. The 16-word state lives in")
w("// `out`; each round is 8 calls of the quarter round `g` with the message")
w("// permutation applied to the arguments. One straight-line function with the")
w("// state in 16 locals runs more instructions when optimized (shared values are")
w("// recomputed at each store) and takes minutes to compile unoptimized in a")
w("// debug compiler; see docs/parallel-results/self-host-std-data.md.")
w("")
w("fn word(in m: Slice[u32], i: u64) -> u32 {")
w("    match m.try_get(i) {")
w("        Option::Some(x) => x,")
w("        Option::None => 0,")
w("    }")
w("}")
w("")
w("// The quarter round on state words `a`, `b`, `c` and `d` of `v`.")
w("fn g(inout v: Slice[u32], a: u64, b: u64, c: u64, d: u64, x: u32, y: u32) {")
w("    let mut va = word(in v, a);")
w("    let mut vb = word(in v, b);")
w("    let mut vc = word(in v, c);")
w("    let mut vd = word(in v, d);")
w("    va = wrapping_add(wrapping_add(va, vb), x);")
w("    vd = rotate_right(vd ^ va, 16);")
w("    vc = wrapping_add(vc, vd);")
w("    vb = rotate_right(vb ^ vc, 12);")
w("    va = wrapping_add(wrapping_add(va, vb), y);")
w("    vd = rotate_right(vd ^ va, 8);")
w("    vc = wrapping_add(vc, vd);")
w("    vb = rotate_right(vb ^ vc, 7);")
w("    v.try_set(a, va);")
w("    v.try_set(b, vb);")
w("    v.try_set(c, vc);")
w("    v.try_set(d, vd);")
w("}")
w("")
w("// Compress the 16 message words `m` into the chaining value `cv` (8 words)")
w("// and write the 16 output words to `out`, which must hold 16 words. Missing")
w("// words read as zero and writes past the end of `out` are dropped, so the")
w("// function is total.")
w("pub fn compress(")
w("    in cv: Slice[u32],")
w("    in m: Slice[u32],")
w("    counter: u64,")
w("    block_len: u32,")
w("    flags: u32,")
w("    inout out: Slice[u32]")
w(") {")
for i in range(16):
    w(f"    let m{i} = word(in m, {i});")
for i in range(8):
    w(f"    out.try_set({i}, word(in cv, {i}));")
for i in range(4):
    w(f"    out.try_set({8 + i}, {IV[i]});")
w("    out.try_set(12, wrapping_u32(counter));")
w("    out.try_set(13, wrapping_u32(counter >> 32));")
w("    out.try_set(14, block_len);")
w("    out.try_set(15, flags);")
sched = list(range(16))
for r in range(7):
    w(f"    // Round {r + 1}.")
    for gi, (a, b, c, d) in enumerate(G):
        w(f"    g(inout out, {a}, {b}, {c}, {d}, m{sched[2 * gi]}, m{sched[2 * gi + 1]});")
    sched = [sched[p] for p in PERM]
for i in range(8):
    w(f"    out.try_set({i}, word(in out, {i}) ^ word(in out, {i + 8}));")
for i in range(8):
    w(f"    out.try_set({i + 8}, word(in out, {i + 8}) ^ word(in cv, {i}));")
w("}")


def straight_line():
    o = []
    v = o.append
    v("fn word(in m: Slice[u32], i: u64) -> u32 {")
    v("    match m.try_get(i) {")
    v("        Option::Some(x) => x,")
    v("        Option::None => 0,")
    v("    }")
    v("}")
    v("")
    v("pub fn compress(in cv: Slice[u32], in m: Slice[u32], counter: u64, block_len: u32, flags: u32, inout out: Slice[u32]) {")
    for i in range(8):
        v(f"    let c{i} = word(in cv, {i});")
    for i in range(16):
        v(f"    let m{i} = word(in m, {i});")
    for i in range(8):
        v(f"    let mut s{i} = c{i};")
    for i in range(4):
        v(f"    let mut s{8 + i}: u32 = {IV[i]};")
    v("    let mut s12 = wrapping_u32(counter);")
    v("    let mut s13 = wrapping_u32(counter >> 32);")
    v("    let mut s14 = block_len;")
    v("    let mut s15 = flags;")
    order = list(range(16))
    for _ in range(7):
        for gi, (a, b, c, d) in enumerate(G):
            x, y = order[2 * gi], order[2 * gi + 1]
            v(f"    s{a} = wrapping_add(wrapping_add(s{a}, s{b}), m{x});")
            v(f"    s{d} = rotate_right(s{d} ^ s{a}, 16);")
            v(f"    s{c} = wrapping_add(s{c}, s{d});")
            v(f"    s{b} = rotate_right(s{b} ^ s{c}, 12);")
            v(f"    s{a} = wrapping_add(wrapping_add(s{a}, s{b}), m{y});")
            v(f"    s{d} = rotate_right(s{d} ^ s{a}, 8);")
            v(f"    s{c} = wrapping_add(s{c}, s{d});")
            v(f"    s{b} = rotate_right(s{b} ^ s{c}, 7);")
        order = [order[p] for p in PERM]
    for i in range(8):
        v(f"    out.try_set({i}, s{i} ^ s{i + 8});")
    for i in range(8):
        v(f"    out.try_set({i + 8}, s{i + 8} ^ c{i});")
    v("}")
    return o


if len(sys.argv) > 2 and sys.argv[2] == "--straight-line":
    out = straight_line()
open(sys.argv[1], "w").write("\n".join(out) + "\n")
