# Generates packages/vesper-std/hash/src/compress.ves: the BLAKE3
# compression function with all 7 rounds unrolled over 16 locals.
PERM = [2, 6, 3, 10, 7, 0, 4, 13, 1, 11, 12, 5, 9, 14, 15, 8]
G = [(0, 4, 8, 12), (1, 5, 9, 13), (2, 6, 10, 14), (3, 7, 11, 15),
     (0, 5, 10, 15), (1, 6, 11, 12), (2, 7, 8, 13), (3, 4, 9, 14)]
out = []
w = out.append
w("// @vesper-std/hash::compress: the BLAKE3 compression function.")
w("//")
w("// Generated by packages/vesper-std/hash/gen/blake3_gen.py from the BLAKE3 reference")
w("// implementation: the 7 rounds are unrolled over 16 `u32` locals, with the")
w("// message permutation applied to the local names, so the state stays in")
w("// registers. Do not edit by hand.")
w("")
w("fn word(in m: Slice[u32], i: u64) -> u32 {")
w("    match m.try_get(i) {")
w("        Option::Some(x) => x,")
w("        Option::None => 0,")
w("    }")
w("}")
w("")
w("// Compress the 16 message words `m` into the chaining value `cv` (8 words)")
w("// and write the 16 output words to `out`. Missing words read as zero and")
w("// writes past the end of `out` are dropped, so the function is total.")
w("pub fn compress(")
w("    in cv: Slice[u32],")
w("    in m: Slice[u32],")
w("    counter: u64,")
w("    block_len: u32,")
w("    flags: u32,")
w("    inout out: Slice[u32]")
w(") {")
for i in range(8):
    w(f"    let c{i} = word(in cv, {i});")
for i in range(16):
    w(f"    let m{i} = word(in m, {i});")
for i in range(8):
    w(f"    let mut s{i} = c{i};")
iv = [0x6A09E667, 0xBB67AE85, 0x3C6EF372, 0xA54FF53A]
for i in range(4):
    w(f"    let mut s{8+i}: u32 = {iv[i]};")
w("    let mut s12 = wrapping_u32(counter);")
w("    let mut s13 = wrapping_u32(counter >> 32);")
w("    let mut s14 = block_len;")
w("    let mut s15 = flags;")
sched = list(range(16))
for r in range(7):
    w(f"    // Round {r + 1}.")
    for gi, (a, b, c, d) in enumerate(G):
        x = sched[2 * gi]
        y = sched[2 * gi + 1]
        w(f"    s{a} = wrapping_add(wrapping_add(s{a}, s{b}), m{x});")
        w(f"    s{d} = rotate_right(s{d} ^ s{a}, 16);")
        w(f"    s{c} = wrapping_add(s{c}, s{d});")
        w(f"    s{b} = rotate_right(s{b} ^ s{c}, 12);")
        w(f"    s{a} = wrapping_add(wrapping_add(s{a}, s{b}), m{y});")
        w(f"    s{d} = rotate_right(s{d} ^ s{a}, 8);")
        w(f"    s{c} = wrapping_add(s{c}, s{d});")
        w(f"    s{b} = rotate_right(s{b} ^ s{c}, 7);")
    sched = [sched[p] for p in PERM]
for i in range(8):
    w(f"    out.try_set({i}, s{i} ^ s{i+8});")
for i in range(8):
    w(f"    out.try_set({i+8}, s{i+8} ^ c{i});")
w("}")
